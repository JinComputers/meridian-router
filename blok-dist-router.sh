#!/bin/sh
# Проверка раздачи ИЗНУТРИ ТУННЕЛЯ, с самого роутера. Ничего не меняет и не
# скачивает боевого — только запрашивает адреса и смотрит коды ответа.
#
# Зачем на роутере, если то же самое гоняется на VPS: там проверка идёт по
# петле, а здесь — через туннель, то есть тем самым путём, которым обновляются
# клиенты с плохим прямым каналом. На Keenetic это уже подтверждено; на OpenWrt
# будет вторым подтверждением на другой платформе.
CAND=http://138.124.78.252:8080/cand-9f4bad1530d654022e91c28b
SEG=cand-9f4bad1530d654022e91c28b
RUN=/tmp/qwdtt-run
WANT=7a6eee0d82056377
mkdir -p $RUN

wget -qO $RUN/check-dist.sh "$CAND/check-dist-access.sh" || echo "не скачался сам скрипт проверки"
GOT=$(sha256sum $RUN/check-dist.sh | cut -c1-16)
echo "check-dist-access.sh: $GOT (ждём $WANT)"
if [ "$GOT" != "$WANT" ]; then
	echo "ВОРОТА ЗАКРЫТЫ: сумма не сошлась, чужой скрипт запускать не буду."
else

echo ""
echo "=== какой адрес шлюза у этого роутера ==="
# У Meridian это 10.77.77.x. Шлюз WG (10.66.66.x) снят 13.09.2026 вместе с
# модулем WireGuard. Берём тот, чья подсеть реально
# есть на интерфейсах: спрашивать несуществующий адрес — это ждать таймаута.
GW=""
ip -4 addr show 2>/dev/null | grep -q 'inet 10\.77\.77\.' && GW=http://10.77.77.1:8080
# /16, а не /24: подсеть WG расширена 25.08.2026 до 10.66.0.0/16, и новые роутеры
# получают 10.66.0.x. Проверка по «10.66.66.» их не узнавала.
if [ -z "$GW" ]; then
	echo "  адреса 10.77.77.x на интерфейсах нет — туннель не поднят."
	echo "  Это не про раздачу: без туннеля проверять внутренний путь нечем."
else
	echo "  шлюз: $GW"
	echo ""
	echo "=== 1. раздача ИЗНУТРИ ТУННЕЛЯ (главное) ==="
	sh $RUN/check-dist.sh "$GW" "$SEG"
fi

echo ""
echo "=== 2. та же проверка ЧЕРЕЗ ПУБЛИЧНЫЙ адрес, для сравнения ==="
echo "  (у клиента с плохим прямым каналом здесь и будут таймауты — это ожидаемо"
echo "   и как раз объясняет, зачем нужен путь через шлюз)"
sh $RUN/check-dist.sh http://138.124.78.252:8080 "$SEG"
fi

echo ""
echo "=== ПРОГОН ДОШЁЛ ДО КОНЦА ==="
