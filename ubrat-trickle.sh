#!/bin/sh
# ubrat-trickle.sh — снять перехват DNS у MagiTrickle ПЕРЕД установкой нашего.
#
# ЗАЧЕМ. 10.09.2026 у клиента 07b5cbed кнопка не поставила DNS. Причина снята с
# живого роутера прогоном исполнителя руками:
#
#     есть чужой заворот DNS: -A MT_DNSOR -d 192.168.1.1/32 --dport 53
#     DNAT --to :3553   ->  установщик код 1, откатился сам
#
# Установщик отказался ПРАВИЛЬНО: два перехватчика на одном потоке не
# сосуществуют — чей заворот раньше, тот и получает запросы, а второй пишет в
# отчёт ноль и выглядит сломанным. Отказ мы не трогаем, это защита в глубину.
# Дыра была в другом: кнопка не снимала трикл перед DNS. Трикл жив у всех
# парковых клиентов, кроме клиента 2 (там его сняли руками ещё до нажатия) —
# то есть на этот отказ упёрся бы каждый.
#
# КОДЫ ВОЗВРАТА — интерфейс, вызывающие судят по ним:
#   0  трикла нет ИЛИ он снят и заворота в nat не осталось
#   1  снять не удалось, чужой заворот на месте (причина напечатана)
#   2  проверка не выполнена: не «хорошо» и не «плохо», мы не узнали
#
# ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО:
#   * УДАЛЕНИЯ. Всё только ПЕРЕИМЕНОВЫВАЕТСЯ, суффиксом .qwdtt-otklyuchen, и
#     команда возврата печатается человеку. Снять чужую программу насовсем мы
#     права не имеем;
#   * прикосновения к конфигу и спискам трикла. /opt/var/lib/magitrickle не
#     открывается даже на чтение: в чужие списки мы не лезем ни при каких
#     обстоятельствах — это стоячее решение владельца;
#   * своей копии опознания «чужого заворота». Окончательный судья — установщик
#     набора DNS, он проверяет это сам и отказывается. Здесь проверка нужна лишь
#     чтобы отказать ЗДЕСЬ и понятно, а не там и загадочно. Поэтому она НИЧЕГО
#     не блокирует: код 1 отсюда не мешает следующему компоненту попробовать.
#
# ИДЕМПОТЕНТНОСТЬ. Второй прогон на снятом трикле не делает ничего и говорит об
# этом. На роутере без трикла — тоже ничего, и без ругани: отсутствие чужой
# программы это не ошибка.

SUF=".qwdtt-otklyuchen"
MT_LIB="/opt/var/lib/magitrickle"          # НЕ ТРОГАЕМ, только смотрим наличие
NFD="/opt/etc/ndm/netfilter.d"
INITD="/opt/etc/init.d"

say() { echo "[trickle] $*"; }

# chuzhoy_zavorot — строки nat, заворачивающие DNS не к себе.
#
# ЧЕСТНО ПРО ЭТОТ ОБРАЗЕЦ. Это ВТОРОЙ экземпляр критерия: первый живёт внутри
# meridian-dns-install.sh и отдельно не вызывается. Дублирование названо вслух,
# потому что копии критериев у нас уже расходились. Здесь копия УЖЕ и слабее:
# она не решает судьбу установки, а только объясняет человеку, что мы видим.
# Собрать их в один вход — в очереди.
chuzhoy_zavorot() {
  iptables -t nat -S 2>/dev/null | awk '
    /--dport 53/ && (/-j DNAT/ || /-j REDIRECT/) && !/_NDM_/ && !/MERIDIAN_DNS/ {
      port = ""
      for (i = 1; i <= NF; i++)
        if ($i == "--to-destination" || $i == "--to-ports") {
          port = $(i+1); sub(/.*:/, "", port)
        }
      if (port != "53") print
    }'
}

# nashi_cepochki — цепочки, которые завёл трикл. Имя берём С РОУТЕРА, а не из
# головы: перечисляем то, что реально объявлено в nat и начинается с MT_.
nashi_cepochki() {
  iptables -t nat -S 2>/dev/null | sed -n 's/^-N \(MT_[A-Za-z0-9_-]*\)$/\1/p'
}

say "=== СНЯТИЕ ПЕРЕХВАТА MagiTrickle, $(date '+%F %T') ==="

# ---------- 1. ЕСТЬ ЛИ ОН ВООБЩЕ ----------
# Признаков три, и любого достаточно. Одного мало: службу могли переименовать,
# правила могли остаться от снятой программы, каталог мог пережить удаление.
INIT_FILE=""
for f in "$INITD"/S*magitrickle* "$INITD"/*magitrickle*; do
  [ -f "$f" ] || continue
  # УЖЕ ОБЕЗВРЕЖЕННОЕ ПРОПУСКАЕМ. Маска *magitrickle* совпадает и с файлом,
  # который мы сами переименовали: без этой строки второй прогон делал бы
  # S99magitrickle.qwdtt-otklyuchen.qwdtt-otklyuchen и с каждым нажатием
  # добавлял ещё один суффикс. Поймано стендом на четвёртом разделе.
  case "$f" in *"$SUF") continue ;; esac
  INIT_FILE="$f"; break
done
KRYUCHKI=""
if [ -d "$NFD" ]; then
  # Крючок ищем ПО СОДЕРЖИМОМУ, а не по имени: имя мы не знаем, а знать обязаны
  # то, что на роутере, а не то, что мы предположили.
  for h in "$NFD"/*; do
    [ -f "$h" ] || continue
    case "$h" in *"$SUF") continue ;; esac
    if grep -qiE 'magitrickle|MT_DNS|3553' "$h" 2>/dev/null; then
      KRYUCHKI="$KRYUCHKI $h"
    fi
  done
fi
ZAV_DO=$(chuzhoy_zavorot)
CEP_DO=$(nashi_cepochki | tr '\n' ' ')

say "--- что нашли"
say "  служба:   ${INIT_FILE:-нет}"
say "  крючки:  ${KRYUCHKI:- нет}"
say "  каталог:  $([ -d "$MT_LIB" ] && echo "есть (не трогаем)" || echo нет)"
say "  цепочки в nat: ${CEP_DO:-нет}"
if [ -n "$ZAV_DO" ]; then
  say "  чужой заворот DNS:"
  echo "$ZAV_DO" | sed 's/^/      /'
else
  say "  чужого заворота DNS нет"
fi

if [ -z "$INIT_FILE" ] && [ -z "$KRYUCHKI" ] && [ -z "$ZAV_DO" ] && [ -z "$CEP_DO" ]; then
  say "MagiTrickle на этом роутере не найден — снимать нечего."
  say "Это не ошибка: у части клиентов его никогда не было."
  exit 0
fi

# ---------- 2. ОСТАНОВКА ----------
if [ -n "$INIT_FILE" ]; then
  say "--- останавливаю службу: $INIT_FILE stop"
  sh "$INIT_FILE" stop < /dev/null 2>&1 | sed 's/^/    /'
  say "  код остановки: $?"
else
  say "--- службы нет, останавливать нечего"
fi

# ---------- 3. КРЮЧОК NETFILTER.D ----------
# Крючок опаснее службы: он возвращает правила при каждой пересборке цепочек
# прошивкой, то есть снятая служба без снятого крючка ничего не решает.
for h in $KRYUCHKI; do
  if mv -f "$h" "$h$SUF" 2>/dev/null; then
    say "  крючок обезврежен: $h -> $h$SUF"
  else
    say "  !!! крючок НЕ переименован: $h"
  fi
done

# ---------- 4. СЛУЖБА ----------
# Переименовываем, чтобы не поднялась при следующей загрузке. Не удаляем.
if [ -n "$INIT_FILE" ]; then
  if mv -f "$INIT_FILE" "$INIT_FILE$SUF" 2>/dev/null; then
    say "  служба обезврежена: $INIT_FILE -> $INIT_FILE$SUF"
  else
    say "  !!! служба НЕ переименована: $INIT_FILE"
  fi
fi

# ---------- 5. ОСТАТКИ ПРАВИЛ ----------
# Правила должна снимать сама служба своим stop. Этот шаг — на случай, когда не
# сняла: тогда чужой заворот остался бы жить без программы, и снять его было бы
# уже некому.
ZAV_POSLE=$(chuzhoy_zavorot)
if [ -n "$ZAV_POSLE" ]; then
  say "--- заворот пережил остановку, снимаю правила поимённо"
  # Только переходы на цепочки MT_*: за пределы этого пространства имён не
  # выходим ни на одну строку.
  iptables -t nat -S 2>/dev/null | grep -E '^-A .* -j MT_' | while read -r _a _cep _rest; do
    if iptables -t nat -D "$_cep" $_rest 2>/dev/null; then
      say "    снят переход: $_cep -> $_rest"
    else
      say "    !!! не снят: -A $_cep $_rest"
    fi
  done
  for c in $(nashi_cepochki); do
    iptables -t nat -F "$c" 2>/dev/null && say "    цепочка $c очищена"
    iptables -t nat -X "$c" 2>/dev/null && say "    цепочка $c удалена"
  done
fi

# ---------- 6. ПРИЁМКА: В nat НЕ ДОЛЖНО ОСТАТЬСЯ НИ ОДНОЙ СТРОКИ ----------
ITOG=$(chuzhoy_zavorot)
CEP_POSLE=$(nashi_cepochki | tr '\n' ' ')
say "--- приёмка"
say "  цепочки MT_ в nat: ${CEP_POSLE:-нет}"
if [ -n "$ITOG" ]; then
  say "КРАСНОЕ: чужой заворот DNS остался:"
  echo "$ITOG" | sed 's/^/      /'
  say "Установка DNS дальше не пройдёт — установщик отказывается на этом сам,"
  say "и это правильно. Пришлите нам эти строки."
  say ""
  say "ВЕРНУТЬ MagiTrickle, если решите отказаться от нашего DNS:"
  [ -n "$INIT_FILE" ] && say "    mv $INIT_FILE$SUF $INIT_FILE"
  for h in $KRYUCHKI; do say "    mv $h$SUF $h"; done
  exit 1
fi
say "чужого заворота DNS в nat не осталось."

# ---------- 7. ЧТО ЭТО ЗНАЧИТ ДЛЯ ЧЕЛОВЕКА ----------
say ""
say "=================================================================="
say "  MagiTrickle ОТКЛЮЧЁН, но НЕ УДАЛЁН."
say "  Его настройки и списки не тронуты — они лежат где лежали."
say "  ВАЖНО, И ЭТО НАДО ПРОЧИТАТЬ ЦЕЛИКОМ."
say "  Если домены у вас ходили через MagiTrickle — СЕЙЧАС ОНИ ХОДИТЬ"
say "  ПЕРЕСТАНУТ. Интернет работает как обычно, перестаёт работать"
say "  именно ОБХОД по этим доменам."
say ""
say "  Наш сервер DNS ставится следующим шагом, но его список ПУСТ:"
say "  мы ничего из MagiTrickle не переносили. Чтобы обход вернулся,"
say "  откройте панель, карточку «Свои маршруты», и впишите свои"
say "  домены туда. Пока список пуст, помечать серверу нечего."
say ""
say "  ВЕРНУТЬ КАК БЫЛО (если решите отказаться от нашего):"
[ -n "$INIT_FILE" ] && say "      mv $INIT_FILE$SUF $INIT_FILE"
for h in $KRYUCHKI; do say "      mv $h$SUF $h"; done
[ -n "$INIT_FILE" ] && say "      sh $INIT_FILE start"
say "=================================================================="
exit 0
