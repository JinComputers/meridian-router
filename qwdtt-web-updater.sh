#!/bin/sh
# qwdtt-web-updater.sh — замена бинаря панели с настоящим бэкапом и автооткатом.
#
# Аргументы (обратно совместимы со старой версией):
#   $1=NEWBIN(.new)  $2=FINALBIN  $3=BAKBIN  $4=PIDFILE  $5=LOGFILE  [$6=WANTSUM]
#
# ПЕРЕПИСАН 17.08.2026 после аварии на роутере владельца. Прежняя версия могла
# оставить человека без панели без пути назад, и оставила: цепочка была такая —
# в /tmp (это ОПЕРАТИВНАЯ память на Keenetic) кончилось место → скачивание дало
# файл нулевой длины → ноль лёг поверх /opt/bin/qwdtt-web → откатываться было
# нечем. Что именно было не так в прежнем скрипте:
#
#   1. Бэкап делался ПЕРЕИМЕНОВАНИЕМ (`mv FINALBIN BAKBIN`) — то есть боевой
#      файл исчезал раньше, чем появлялся новый, и годность копии не проверялась
#      вовсе. Плюс через 3 секунды бэкап УДАЛЯЛСЯ, даже если панель на самом деле
#      уже не отвечала.
#   2. Единственной проверкой нового файла было `-s` (непустой). Обрезанный
#      наполовину бинарь её проходит.
#   3. Признаком успеха считалось «процесс жив 3 секунды». Процесс может быть жив
#      и не обслуживать порт; и наоборот, панель поднимается дольше 3 секунд.
#   4. Лог панели при рестарте затирался (`> LOG`), поэтому причина падения
#      исчезала вместе с падением.
#
# Порядок теперь такой: проверить новый файл → сделать и ПРОВЕРИТЬ бэкап →
# подменить атомарно → поднять → убедиться, что панель ОТВЕЧАЕТ → при неудаче
# вернуть бэкап и сказать об этом явным текстом. Ни один шаг не удаляет
# единственную копию рабочего бинаря.
#
# Код возврата: 0 — обновлено и проверено; 1 — не обновлялось (боевой файл не
# тронут); 2 — обновление откатано; 3 — откат НЕ УДАЛСЯ (нужны руки).

# --consume — «файл мой, можешь его забрать». По умолчанию ВЫКЛЮЧЕН.
#
# Правка 18.08.2026 по замечанию владельца: апдейтер удалял файл, который создал
# не он. На прогоне это увидели дважды — и после отказа по месту, и после успеха
# исчезал /tmp/qwdtt-run/web.v61, положенный туда человеком. Скрипт вправе
# убирать только то, что создал сам; всё остальное убирает тот, кто создал.
#
# Поэтому теперь по умолчанию новый файл КОПИРУЕТСЯ на раздел цели во временное
# имя, и подменяется именно копия. Исходный файл остаётся лежать, где лежал, при
# любом исходе. С --consume поведение прежнее: файл переносится и при отказе
# удаляется — так дешевле по месту, и панель может им пользоваться осознанно.
CONSUME=0
_left=$#
while [ "$_left" -gt 0 ]; do
	_a="$1"; shift
	if [ "$_a" = "--consume" ]; then
		CONSUME=1
	else
		set -- "$@" "$_a"
	fi
	_left=$((_left - 1))
done

NEWBIN="$1"
FINALBIN="$2"
BAKBIN="$3"
PIDFILE="$4"
LOGFILE="$5"
WANTSUM="$6"

[ -n "$NEWBIN" ] && [ -n "$FINALBIN" ] && [ -n "$BAKBIN" ] && [ -n "$PIDFILE" ] && [ -n "$LOGFILE" ] || {
	echo "использование: $0 [--consume] NEWBIN FINALBIN BAKBIN PIDFILE LOGFILE [SHA256]" >&2
	exit 1
}

# STAGED=1 означает «файл под $NEWBIN сделали мы сами», то есть его можно убирать.
STAGED=0

# fsize объявлена ЗДЕСЬ, а не ниже, потому что первое её использование — потолок
# собственного лога десятью строками ниже. Оболочка читает файл сверху вниз: до
# объявления функции ещё нет, вызов даёт «fsize: not found», ошибка печатается —
# и выполнение ИДЁТ ДАЛЬШЕ. Обновление объявляло успех, а потолок лога не
# работал ни разу (найдено 08.09.2026 на волне ноль, дефект жил с версии 4.4).
# Сторож на это — /root/kot2/check-func-order.sh, раздел в test-scripts.sh.
# fsize — размер файла в байтах или 0, если файла нет.
#
# Через группировку, а не просто `wc -c < файл 2>/dev/null`: при отсутствии файла
# ошибку перенаправления печатает ОБОЛОЧКА, до запуска wc, и `2>/dev/null` на
# самой команде её не перехватывает. Это тот же дефект, что вылез с
# /proc/<pid>/cmdline: строка «can't open …» там, где мы уже всё предусмотрели.
fsize() {
	_s=$( { wc -c < "$1"; } 2>/dev/null | tr -d ' \t' )
	[ -n "$_s" ] || _s=0
	echo "$_s"
}

UPDLOG="$LOGFILE.updater"
# Свой лог тоже под потолком: он растёт при каждом обновлении, а места на флеше
# 46 МБ (правило 21 — лог без потолка это отложенная утечка, просто медленная).
UPDLOG_MAX=131072
if [ -f "$UPDLOG" ] && [ "$(fsize "$UPDLOG")" -gt "$UPDLOG_MAX" ] 2>/dev/null; then
	tail -c "$UPDLOG_MAX" "$UPDLOG" > "$UPDLOG.trim" 2>/dev/null && mv -f "$UPDLOG.trim" "$UPDLOG" 2>/dev/null
	rm -f "$UPDLOG.trim" 2>/dev/null
fi
PORT_HEX=1F9A   # 8090 — порт панели, в /proc/net/tcp он шестнадцатеричный
# 20 попыток по 1 секунде: панель на MIPS поднимается не мгновенно. Переменная —
# ТОЛЬКО для прогонов: без неё каждый тест ждёт свои двадцать секунд, и полный
# набор перестаёт умещаться в разумное время (18.08.2026 перестал).
HEALTH_TRIES="${QWDTT_HEALTH_TRIES:-20}"

log() {
	echo "$(date '+%Y-%m-%d %H:%M:%S') $1" >> "$UPDLOG"
	echo "$1"
}


# df: ключ -P (POSIX-вывод) есть не в каждой сборке BusyBox, а без него команда
# не «работает хуже», а падает целиком — и место остаётся непроверенным молча.
# Поэтому возможность проверяется один раз при старте, с откатом на голый -k.
DF_OPT="-Pk"
df $DF_OPT / >/dev/null 2>&1 || DF_OPT="-k"

df_field() { df $DF_OPT "$1" 2>/dev/null | awk -v c="$2" 'NR==2{print $c}'; }
fs_of()    { df_field "$1" 1; }

# drop_new — убрать новый файл, но ТОЛЬКО если он наш: либо мы его сами скопировали
# на раздел цели, либо вызывающий явно сказал --consume. Чужой файл не трогаем
# никогда, даже при отказе: удалять чужое — не работа этого скрипта.
drop_new() {
	if [ "$STAGED" = 1 ] || [ "$CONSUME" = 1 ]; then
		rm -f "$NEWBIN"
	fi
}

# kill_panels — добить процессы панели, НЕ ТРОГАЯ СЕБЯ.
#
# Было: `ps w | grep '[q]wdtt-web' | awk '{print $1}'`. На GNU-машине `ps w` без
# ключей показывает лишь процессы своего терминала, и в прогонах это выглядело
# безобидно. BusyBox ps показывает ВСЕ процессы всегда — а в командной строке
# самого апдейтера стоит и его имя (`qwdtt-web-updater.sh`), и путь к панели.
# То есть на роутере этот цикл убивал сам апдейтер: панель остановлена, новый
# файл ещё не подменён, поднимать некому. Найдено 18.08.2026 прогоном в среде
# клиента (test-busybox.sh), на VPS не воспроизводилось вовсе.
#
# Теперь без ps: /proc есть всегда, а сравнение идёт с ПОЛНЫМ путём панели, а не
# с куском имени. Свой PID и всё, что похоже на апдейтер, пропускаются.
kill_panels() {
	for d in /proc/[0-9]*; do
		p="${d#/proc/}"
		[ "$p" = "$$" ] && continue
		# Процесс мог завершиться между `for` и этой строкой — и это ЖЕЛАЕМЫЙ
		# исход, а не сбой. Ошибку перенаправления печатает САМА ОБОЛОЧКА, и
		# `2>/dev/null` на команде её не ловит: человек видел
		# «can't open /proc/<pid>/cmdline» после успешного обновления и решал,
		# что сломалось. Проверка + группировка: проверка снимает обычный
		# случай, группировка — гонку между проверкой и чтением.
		[ -r "$d/cmdline" ] || continue
		cmd=$( { tr '\0' ' ' < "$d/cmdline"; } 2>/dev/null )
		case "$cmd" in
			*updater*) continue ;;
			*"$FINALBIN"*)
				kill "$p" 2>/dev/null
				log "добит процесс панели PID $p"
				;;
		esac
	done
}

# Порт панели слушается? Проверка без внешних зависимостей: /proc/net/tcp есть
# всегда, а wget/curl на роутере может не быть или быть урезанным.
#
# ОБА файла, tcp и tcp6, и это не перестраховка: панель написана на Go, а
# ListenAndServe(":8090") садится на двойной стек, то есть сокет виден ТОЛЬКО в
# /proc/net/tcp6. С проверкой одного /proc/net/tcp здоровая панель считалась
# мёртвой, и апдейтер откатывал удачное обновление (поймано прогоном).
port_listening() {
	for f in /proc/net/tcp /proc/net/tcp6; do
		[ -r "$f" ] || continue
		if awk -v p=":$PORT_HEX" '$2 ~ p"$" && $4 == "0A" {found=1} END{exit !found}' "$f" 2>/dev/null; then
			return 0
		fi
	done
	return 1
}

# Панель ОТВЕЧАЕТ по HTTP? 401 — это тоже ответ (пароль включён), и он
# доказывает, что обработчики живы. Отсутствие вывода вовсе — не доказывает.
http_answers() {
	if command -v wget >/dev/null 2>&1; then
		wget -q -O - "http://127.0.0.1:8090/healthz" 2>/dev/null | grep -q . && return 0
		# У панелей до 5.1 нет /healthz: любой ответ с корня тоже годится.
		wget -q -O - "http://127.0.0.1:8090/" 2>/dev/null | grep -q . && return 0
		wget -q -O /dev/null "http://127.0.0.1:8090/" 2>&1 | grep -q '401' && return 0
	fi
	return 1
}

# Панель жива: процесс есть, порт слушается. HTTP-ответ — сильный признак, но
# необязательный: на роутере с включённым паролем busybox-wget умеет вернуть
# пустой вывод, и тогда решает порт.
alive() {
	PID="$1"
	kill -0 "$PID" 2>/dev/null || return 1
	port_listening || return 1
	return 0
}

# panel_process_alive — есть ли ЖИВОЙ процесс, исполняющий ИМЕННО наш файл.
# Сравниваем цель /proc/N/exe целиком: путь панели содержит путь клиента как
# подстроку, и сравнение вхождением однажды уже приняло панель за клиента.
panel_process_alive() {
	for _d in /proc/[0-9]*; do
		_t=$(readlink "$_d/exe" 2>/dev/null)
		case "$_t" in *" (deleted)") _t="${_t% (deleted)}" ;; esac
		[ "$_t" = "$FINALBIN" ] && return 0
	done
	return 1
}

# ЗДОРОВЬЕ СУДИМ ПО СЛУЖБЕ, А НЕ ПО СВОЕМУ PID.
#
# 08.09.2026, прогон 6.24 у владельца: в журнале две строки «слушает :8090» с
# разницей в секунду и «bind: address already in use». Второй запуск — СТОРОЖ
# init панели: он тикает раз в минуту (qwdtt-web-init-entware.sh:45 WDEVERY=60),
# и если тик попал в окно подмены, делает stop_quiet; sleep 1; start_quiet
# (:86-88). Сторож — оболочка init, а не бинарь панели, поэтому kill_panels его
# не трогает и подмену он переживает.
#
# ЧЕМ ЭТО ОПАСНО. Сторож может остановить панель ПОСЛЕ того, как её поднял
# апдейтер. Тогда наш $NEWPID мёртв, `alive` возвращает ложь — и апдейтер
# ОТКАТЫВАЕТ ИСПРАВНУЮ НОВУЮ ПАНЕЛЬ, которую в этот момент уже поднял сторож
# из НОВОГО же бинаря. Окно — секунды подмены против тика раз в минуту: на одном
# роутере это редкость, на одиннадцати — почти наверняка.
#
# Лечим не гашением сторожа, а тем, что перестаём считать «моё дитя живо»
# признаком здоровья. Признак — СЛУЖБА ОТВЕТИЛА; чей это процесс, неважно.
# Гасить сторож апдейтером нельзя одним файлом: watchdog_start снаружи не
# вызывается (у init нет такого глагола), а start) при живой панели уходит на
# «уже запущен» РАНЬШЕ него (:start early return) — то есть сторож остался бы
# мёртвым до перезагрузки, и упавшую панель некому было бы поднять.
sluzhba_otvechaet() {
	if http_answers; then return 0; fi
	# Ответа ещё нет — но панель могла только что подняться. Порт, занятый
	# НАШИМ файлом, тоже признак: это ровно тот случай, когда процесс поднял
	# сторож, а не мы.
	port_listening || return 1
	panel_process_alive || return 1
	return 0
}

# start_panel — поднять панель и положить её PID в PANEL_PID.
#
# PID отдаётся ПЕРЕМЕННОЙ, а не через stdout: log() печатает и в файл, и на
# экран, поэтому `PID=$(start_panel)` подхватывал бы строку журнала вместе с
# числом. Именно на этом прогон поймал ложный «откат удачного обновления».
ROTATED=0
start_panel() {
	# Лог НЕ затираем: причина прошлого падения — единственная улика, и терять
	# её при каждом рестарте нельзя (авария 17.08.2026: панель упала с дампом
	# горутин, лог обнулили рестартом раньше, чем сохранили).
	#
	# И ровно ОДИН РАЗ за прогон. Первая версия этой правки поворачивала лог на
	# каждом запуске, то есть при откате втрое: .log.1 сначала получал улику
	# прошлого запуска, а через двадцать секунд — вывод не поднявшейся новой
	# панели, и улика терялась ТЕМ ЖЕ СПОСОБОМ, от которого мы её спасаем.
	# Поймано прогоном (случай «служба не поднялась»).
	if [ "$ROTATED" = 0 ] && [ -s "$LOGFILE" ]; then
		mv -f "$LOGFILE" "$LOGFILE.1" 2>/dev/null && log "прошлый лог сохранён как $(basename "$LOGFILE").1"
		ROTATED=1
	fi
	"$FINALBIN" < /dev/null >> "$LOGFILE" 2>&1 &
	PANEL_PID=$!
	echo "$PANEL_PID" > "$PIDFILE"
}

log "=== обновление панели начато (новый файл: $NEWBIN) ==="

# ---------- 1. Новый файл: непустой, ELF, нужного размера, верной суммы ----------
if [ ! -f "$NEWBIN" ]; then
	log "ОТКАЗ: нового файла нет — боевая панель не тронута"
	exit 1
fi
NEWSIZE=$(fsize "$NEWBIN")
[ -n "$NEWSIZE" ] || NEWSIZE=0
if [ "$NEWSIZE" -lt 1000000 ]; then
	# Именно здесь ловится авария: пустой файл (0 байт) и обрезанный (109 КБ из
	# 2,4 МБ — ровно столько успело записаться в переполненную память).
	log "ОТКАЗ: новый файл $NEWSIZE Б, это меньше миллиона — скачивание оборвалось. Боевая панель не тронута."
	drop_new
	exit 1
fi
# ELF проверяется БЕЗ od: в BusyBox на Keenetic у od нет ключа -A, и прежняя
# строка `od -An -c` падала с «od: invalid option -- 'A'» на КАЖДОМ Кинетике.
# Отказ при этом выглядел осмысленно («новый файл не ELF»), поэтому дефект жил
# в боевых скриптах 4.5 и означал, что панель там не обновляется никогда.
# `head -c` и `grep` есть в любой сборке BusyBox; ровно этим же способом
# проверяет install.sh.
if head -c 4 "$NEWBIN" 2>/dev/null | grep -q ELF; then
	:
else
	log "ОТКАЗ: новый файл не начинается с ELF — возможно, скачалась страница ошибки. Боевая панель не тронута."
	drop_new
	exit 1
fi
if [ -n "$WANTSUM" ]; then
	if command -v sha256sum >/dev/null 2>&1; then
		GOTSUM=$(sha256sum "$NEWBIN" | awk '{print $1}')
		if [ "$GOTSUM" != "$WANTSUM" ]; then
			log "ОТКАЗ: сумма не совпала с опубликованной"
			log "  ожидали: $WANTSUM"
			log "  получили: $GOTSUM"
			drop_new
			exit 1
		fi
		log "сумма совпала с опубликованной ($(echo "$GOTSUM" | cut -c1-16))"
	else
		# Не отказ: на части прошивок sha256sum нет вовсе, и запрет означал бы
		# «обновиться нельзя никогда». Но в лог это идёт заметной строкой.
		log "ВНИМАНИЕ: sha256sum на этом роутере нет — сумма НЕ проверена, только размер и ELF"
	fi
else
	log "ВНИМАНИЕ: сумма не передана — проверены только размер и ELF"
fi
log "новый файл принят: $NEWSIZE Б, ELF"

# ---------- 2а. Ровно ОДИН бэкап на компонент ----------
#
# Снимаем лишние копии ДО подсчёта места: они и есть то место. Отказать, не убрав
# своё же старьё, значит потребовать от человека делать нашу работу руками.
#
# Иначе каждое обновление оставляет ещё одну копию по 2,4 МБ, и на флеше 46 МБ это
# кончается тем, чем кончилось 17.08: свободно 9,6 МБ, из них 8 МБ — наши же копии.
# Снимаем ТОЛЬКО производные от имени цели и ТОЛЬКО в двух известных каталогах;
# сам боевой файл и файл с боевым именем не трогаем никогда.
FINALNAME=$(basename "$FINALBIN")
FINALDIR=$(dirname "$FINALBIN")
BAKDIR=$(dirname "$BAKBIN")
[ -d "$BAKDIR" ] || mkdir -p "$BAKDIR" 2>/dev/null
for old in "$FINALDIR/$FINALNAME".bak "$FINALDIR/$FINALNAME".bak.* \
           "$FINALDIR/$FINALNAME".prev.* "$FINALDIR/$FINALNAME".old \
           "$BAKDIR/$FINALNAME".bak.* "$BAKDIR/$FINALNAME".prev.* \
           "$BAKDIR/$FINALNAME".old "$BAKDIR/$FINALNAME".[0-9]*; do
	[ -e "$old" ] || continue
	[ "$old" = "$FINALBIN" ] && continue
	[ "$old" = "$BAKBIN" ] && continue
	[ "$(basename "$old")" = "$FINALNAME" ] && continue
	sz=$(fsize "$old")
	rm -f "$old" 2>/dev/null && log "снят лишний бэкап: $old (${sz:-0} Б) — держим один на компонент"
done

# ---------- 2б. Свободного места хватит на НОВЫЙ ФАЙЛ ПЛЮС БЭКАП? ----------
#
# СТОИТ ДО переноса файла на раздел цели, и это не косметика: с обратным порядком
# нехватка места вылезала общим «не удалось перенести файл (место?)», а человеку
# нужно знать, СКОЛЬКО не хватает и что делать. Поймано тестом 17.08.2026.
#
# Проверка до первой записи, а не после неудачи. 17.08.2026 мы уже видели, чем
# кончается запись при нехватке: файл нулевой длины поверх работающей панели.
# Считаем то, что реально предстоит записать на раздел цели:
#   - бэкап боевого файла (его размер), всегда;
#   - сам новый файл — только если он ещё не на этом разделе (если уже здесь, его
#     байты уже заняты и второй раз их считать нельзя).
# Плюс запас 256 КБ на служебное: без запаса «ровно впритык» — это то же самое,
# что без места.
NEED_KB=0
if [ -f "$FINALBIN" ]; then
	NEED_KB=$(( ($(fsize "$FINALBIN") + 1023) / 1024 ))
fi
FS_BAK=$(fs_of "$BAKDIR")
FS_NEWNOW=$(fs_of "$NEWBIN")
# Байты нового файла считаем, если ему предстоит лечь на раздел цели ЕЩЁ РАЗ:
# он либо на другом разделе, либо мы будем копировать его рядом с целью, потому
# что забирать чужой файл переименованием нам нельзя (см. --consume).
if [ "$FS_NEWNOW" != "$(fs_of "$(dirname "$FINALBIN")")" ] || [ "$CONSUME" = 0 ]; then
	NEED_KB=$((NEED_KB + (NEWSIZE + 1023) / 1024))
fi
NEED_KB=$((NEED_KB + 256))
AVAIL_KB=$(df_field "$BAKDIR" 4)
# Пустой ответ df — это НЕ «места хватает». Молча пропущенная проверка выглядит
# в логе как успешное обновление, а кончается нулевым файлом поверх панели.
[ -n "$AVAIL_KB" ] || log "ВНИМАНИЕ: df на этом роутере не отвечает (ключи: $DF_OPT) — свободное место НЕ проверено"
if [ -n "$AVAIL_KB" ] && [ "$AVAIL_KB" -lt "$NEED_KB" ] 2>/dev/null; then
	log "ОТКАЗ: не хватает места. Нужно $NEED_KB КБ (новый файл плюс бэкап и запас), свободно $AVAIL_KB КБ — не хватает $((NEED_KB - AVAIL_KB)) КБ."
	log "  освободить: qwdtt-ctl cleanup   (снимет лишние бэкапы, обрывки и прогоны)"
	log "  боевая панель НЕ тронута, обновление не начиналось"
	drop_new
	exit 1
fi
[ -n "$AVAIL_KB" ] && log "места хватает: нужно $NEED_KB КБ, свободно $AVAIL_KB КБ"

# ---------- 2в. Новый файл обязан лежать на том же разделе, что цель ----------
#
# Иначе подмена перестаёт быть атомарной (mv между ФС — это копирование), а
# скачивание идёт в /tmp, то есть в оперативную память: именно из-за этого и
# получился нулевой файл. Если раздел другой — переносим сами, с проверкой.
FS_NEW=$(fs_of "$NEWBIN")
FS_FIN=$(fs_of "$FINALBIN")
OTHER_FS=0
if [ -n "$FS_NEW" ] && [ -n "$FS_FIN" ] && [ "$FS_NEW" != "$FS_FIN" ]; then
	OTHER_FS=1
fi
# Копию делаем ВСЕГДА, кроме случая «--consume и файл уже на нужном разделе»:
# без --consume файл чужой, и забирать его переименованием нельзя.
if [ "$OTHER_FS" = 1 ] || [ "$CONSUME" = 0 ]; then
	if [ "$OTHER_FS" = 1 ]; then
		log "новый файл на другом разделе ($FS_NEW против $FS_FIN) — копирую рядом с целью"
	else
		log "копирую новый файл рядом с целью (исходный не мой — оставляю на месте)"
	fi
	SAMEFS="$FINALBIN.incoming"
	rm -f "$SAMEFS"
	if ! cat "$NEWBIN" > "$SAMEFS" 2>/dev/null; then
		log "ОТКАЗ: не удалось положить файл на раздел цели (место?) — боевая панель не тронута"
		rm -f "$SAMEFS"
		drop_new
		exit 1
	fi
	MOVEDSIZE=$(fsize "$SAMEFS")
	if [ "$MOVEDSIZE" != "$NEWSIZE" ]; then
		log "ОТКАЗ: копия неполная ($MOVEDSIZE из $NEWSIZE Б) — боевая панель не тронута"
		rm -f "$SAMEFS"
		drop_new
		exit 1
	fi
	# Исходник убираем ТОЛЬКО если он наш по договорённости (--consume).
	drop_new
	NEWBIN="$SAMEFS"
	STAGED=1
	log "копия на разделе цели готова: $MOVEDSIZE Б"
fi

# ---------- 3. Настоящий бэкап: КОПИЯ, проверенная по размеру ----------
if [ ! -f "$FINALBIN" ]; then
	log "боевого файла нет вовсе — ставлю новый как первый (откатываться не на что)"
else
	OLDSIZE=$(fsize "$FINALBIN")
	[ -n "$OLDSIZE" ] || OLDSIZE=0
	rm -f "$BAKBIN"
	# cp, а не mv: боевой файл обязан оставаться на месте до самой подмены.
	if ! cp "$FINALBIN" "$BAKBIN" 2>/dev/null; then
		log "ОТКАЗ: бэкап не сделан (нет места?) — обновление НЕ начинаю, панель работает как была"
		drop_new; rm -f "$BAKBIN"
		exit 1
	fi
	BAKSIZE=$(fsize "$BAKBIN")
	[ -n "$BAKSIZE" ] || BAKSIZE=0
	if [ "$BAKSIZE" = 0 ] || [ "$BAKSIZE" != "$OLDSIZE" ]; then
		log "ОТКАЗ: бэкап негодный ($BAKSIZE Б против $OLDSIZE Б) — обновление НЕ начинаю"
		drop_new; rm -f "$BAKBIN"
		exit 1
	fi
	chmod +x "$BAKBIN" 2>/dev/null
	log "бэкап проверен: $BAKBIN, $BAKSIZE Б"
fi

# ---------- 4. Останов и АТОМАРНАЯ подмена ----------
OLDPID=$(cat "$PIDFILE" 2>/dev/null)
if [ -n "$OLDPID" ]; then
	kill "$OLDPID" 2>/dev/null
	log "остановлен старый процесс PID $OLDPID"
fi
# Добиваем всё, что осталось: два процесса панели на 248 МБ памяти — это уже
# половина следующей аварии.
kill_panels
sleep 2

# mv на том же разделе меняет запись в каталоге, не трогая занятый inode: cp
# поверх работающего файла молча падает с ETXTBSY.
if ! mv -f "$NEWBIN" "$FINALBIN"; then
	log "СБОЙ: подмена не удалась, возвращаю бэкап"
	if [ -f "$BAKBIN" ]; then
		cp "$BAKBIN" "$FINALBIN" && chmod +x "$FINALBIN"
	fi
	start_panel
	log "поднята прежняя панель, PID $PANEL_PID"
	exit 2
fi
chmod +x "$FINALBIN"
log "бинарь подменён"

# ---------- 5. Подъём и проверка ЗДОРОВЬЯ ----------
start_panel
NEWPID=$PANEL_PID
log "запущен новый процесс PID $NEWPID"

I=0
OK=0
while [ "$I" -lt "$HEALTH_TRIES" ]; do
	sleep 1
	I=$((I + 1))
	if sluzhba_otvechaet; then
		if ! kill -0 "$NEWPID" 2>/dev/null; then
			log "панель отвечает, но это НЕ наш процесс (наш $NEWPID уже мёртв) —"
			log "  скорее всего в окно подмены вмешался сторож init; для обновления это удача, а не беда"
		fi
		if http_answers; then
			log "ОК: панель отвечает по HTTP (за $I с)"
		else
			log "ОК: процесс жив и порт 8090 слушается (за $I с); HTTP-ответ не получен, но это может быть пароль"
		fi
		OK=1
		break
	fi
done

if [ "$OK" = 1 ]; then
	# Бэкап НЕ удаляем: он стоит 2,4 МБ и однажды уже был нужен. Следующее
	# обновление перезапишет его само.
	log "=== обновление завершено успешно, бэкап оставлен на месте: $BAKBIN ==="
	exit 0
fi

# ---------- 6. Автооткат ----------
log "СБОЙ: новая панель не поднялась за $HEALTH_TRIES с (процесс и/или порт 8090 недоступны) — откатываюсь"
kill "$NEWPID" 2>/dev/null
kill_panels
sleep 2

if [ ! -f "$BAKBIN" ]; then
	log "!!! ОТКАТ НЕВОЗМОЖЕН: бэкапа нет. Панель не работает."
	log "!!! Руками: wget -O /opt/bin/qwdtt-web.new http://<адрес>/bin/qwdtt-web-<арх> && [ -s ... ] && mv -f /opt/bin/qwdtt-web.new /opt/bin/qwdtt-web && chmod +x /opt/bin/qwdtt-web"
	exit 3
fi
# Лог неудачной попытки — вторая улика, и она НЕ должна смешаться с первой.
if [ -s "$LOGFILE" ]; then
	cp "$LOGFILE" "$LOGFILE.failed" 2>/dev/null && log "вывод не поднявшейся версии сохранён как $(basename "$LOGFILE").failed"
fi
rm -f "$FINALBIN.failed"
mv -f "$FINALBIN" "$FINALBIN.failed" 2>/dev/null
if ! cp "$BAKBIN" "$FINALBIN"; then
	log "!!! ОТКАТ НЕ УДАЛСЯ: бэкап есть ($BAKBIN), но скопировать его не получилось. Панель не работает."
	exit 3
fi
chmod +x "$FINALBIN"
start_panel
BACKPID=$PANEL_PID
I=0
while [ "$I" -lt "$HEALTH_TRIES" ]; do
	sleep 1
	I=$((I + 1))
	if alive "$BACKPID"; then
		log "ОТКАТ ВЫПОЛНЕН: вернулась прежняя панель (PID $BACKPID, за $I с)."
		log "Новая версия НЕ установлена. Неудачный файл оставлен как $FINALBIN.failed — не удаляй его, он нужен для разбора."
		exit 2
	fi
done
log "!!! ОТКАТ ВЫПОЛНЕН ФАЙЛОМ, НО ПАНЕЛЬ НЕ ПОДНЯЛАСЬ. Нужны руки: проверь $LOGFILE и $UPDLOG."
exit 3
