# rb_chelovek — ЧИТАЕМАЯ дата следа отката.
#
# Голая метка «1788542172» человеку не говорит ничего, а строка существует
# ровно для человека. Дефект записан 04.09.2026 и это его третий экземпляр
# подряд — поэтому перевод стоит в ОБОИХ местах, где след показывают
# (здесь и `rollback-ack` в init-скрипте), и оба закрыты стендом. Сторож у
# одной двери из двух не сторож (правило 43).
#
# at_human пишет сам установщик (с 0.3), и он ВЕРНЕЕ перевода задним числом:
# часовой пояс роутера мог смениться между откатом и показом.
#
# Способ перевода ВЫБИРАЕТСЯ ПРОБОЙ, а не предполагается: `date -d @N` есть в
# GNU и в части сборок BusyBox, `date -D %s -d N` — busybox-специфичный, и
# обеих форм на роутере может не быть (правило 25). Не вышло ни одной — так и
# говорим, а не печатаем пустоту, которую примут за дату.
rb_chelovek() {
    _w=$(sed -n 's/^at_human=//p' "$ROLLBACKMARK" 2>/dev/null | head -1)
    if [ -n "$_w" ]; then
        echo "$_w"
        return 0
    fi
    _t=$(sed -n 's/^at=//p' "$ROLLBACKMARK" 2>/dev/null | head -1)
    case "$_t" in ''|*[!0-9]*) echo "время в следе не записано"; return 0 ;; esac
    _h=$(date -d "@$_t" '+%Y-%m-%d %H:%M:%S' 2>/dev/null)   # bb-ok: результат проверяется, есть запасные пути
    if [ -n "$_h" ]; then
        echo "$_h"
        return 0
    fi
    _h=$(date -D %s -d "$_t" '+%Y-%m-%d %H:%M:%S' 2>/dev/null)   # bb-ok: то же
    if [ -n "$_h" ]; then
        echo "$_h"
        return 0
    fi
    echo "date этой сборки метку $_t не переводит"
}

# ZHIVOE — тронуто ли живое (init подменён, сервер останавливался). До этого
# откату возвращать нечего: снимаем свои временные файлы и копии и выходим,
# не дёргая работающий DNS дома.
ZHIVOE=0
KONF_OTLOZHEN=0
rollback() {
    WHY="$1"
    # Откат не прерывается: второй Ctrl+C посреди возврата хуже первого.
    trap '' INT TERM HUP
    rm -f "$BIN.incoming" "$INIT.incoming" "$HOOK.incoming" 2>/dev/null
    if [ "$ZHIVOE" = 0 ]; then
        echo "[meridian-dns] ОТКАЗ: $WHY" >&2
        rm -f "$BAKDIR/meridian-dns.prev" "$BAKDIR/meridian-dns-init.prev" 2>/dev/null
        echo "[meridian-dns] живое не тронуто: прежний сервер работает как работал, временные файлы сняты" >&2
        exit 1
    fi
    echo "[meridian-dns] ОТКАТ: $WHY" >&2
    # След ставим ПЕРВЫМ делом: если дальше что-то пойдёт не так, человек всё
    # равно узнает, что откат был и почему.
    mkdir -p "$(dirname "$ROLLBACKMARK")" 2>/dev/null
    { echo "at=$(date +%s)"
      echo "at_human=$(date '+%Y-%m-%d %H:%M:%S')"
      echo "reason=selfcheck_failed"
      echo "effect=previous_version_restored"
      echo "note=$WHY"
    } > "$ROLLBACKMARK.tmp" 2>/dev/null && mv -f "$ROLLBACKMARK.tmp" "$ROLLBACKMARK" 2>/dev/null
    [ -x "$INIT" ] && "$INIT" stop >/dev/null 2>&1
    "$BIN" off >/dev/null 2>&1
    if [ "$HADBIN" = 1 ]; then
        # ВОЗВРАТ ПЕРЕНОСОМ, НЕ КОПИЕЙ (правило 25.09.2026): mv на том же разделе
        # места не требует, cp потребовал бы ещё целый модуль ровно тогда, когда
        # места может не быть вовсе. Проверка — размером (правило 37).
        # Модуль ещё не подменялся — копия и модуль одна жёсткая ссылка, mv
        # такого ответит «один и тот же файл». Возвращать нечего: снимаем ссылку.
        if [ "$BAKDIR/meridian-dns.prev" -ef "$BIN" ]; then
            rm -f "$BAKDIR/meridian-dns.prev"
            echo "[meridian-dns] модуль не подменялся — на месте прежний" >&2
        elif mv -f "$BAKDIR/meridian-dns.prev" "$BIN" 2>/dev/null \
           && [ "$(wc -c < "$BIN" 2>/dev/null)" = "$OLDBIN_B" ]; then
            echo "[meridian-dns] прежний бинарь возвращён" >&2
        else
            echo "[meridian-dns] ВНИМАНИЕ: прежний бинарь ВЕРНУТЬ НЕ УДАЛОСЬ. Вручную:" >&2
            echo "    mv -f $BAKDIR/meridian-dns.prev $BIN" >&2
        fi
    else
        rm -f "$BIN"
        echo "[meridian-dns] бинаря не было — удалён" >&2
    fi
    if [ "$HADINIT" = 1 ]; then
        if [ "$BAKDIR/meridian-dns-init.prev" -ef "$INIT" ]; then
            rm -f "$BAKDIR/meridian-dns-init.prev"
        else
            mv -f "$BAKDIR/meridian-dns-init.prev" "$INIT" 2>/dev/null \
            || echo "[meridian-dns] ВНИМАНИЕ: прежний init вернуть не удалось. Вручную: mv -f $BAKDIR/meridian-dns-init.prev $INIT" >&2
        fi
    else
        rm -f "$INIT"
    fi
    # Прежний конфиг, отложенный в .was этой установкой, возвращается на место
    # тем же переносом: откат — к состоянию ДО запуска, а не «почти».
    if [ "$KONF_OTLOZHEN" = 1 ] && [ -f "$CONF.was" ]; then
        mv -f "$CONF.was" "$CONF" 2>/dev/null \
            && echo "[meridian-dns] прежний конфиг возвращён из $CONF.was" >&2
    fi
    if [ "$HADCRON" = 0 ] && [ -f "$CRONFILE" ]; then
        grep -vF "$CRONMARK" "$CRONFILE" > "$CRONFILE.tmp" 2>/dev/null
        mv -f "$CRONFILE.tmp" "$CRONFILE" 2>/dev/null
    fi
    if [ "$HADBIN" = 1 ] && [ "$HADINIT" = 1 ]; then
        "$INIT" start >/dev/null 2>&1 && echo "[meridian-dns] прежняя версия запущена" >&2
    fi
    echo "[meridian-dns] состояние возвращено к прежнему. Интернет в доме работает как до установки." >&2
    echo "[meridian-dns] после отката свободно $(svobodno_kb) КБ" >&2
    exit 1
}

