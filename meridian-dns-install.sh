#!/bin/sh
# meridian-dns-install.sh — установка сервера DNS С САМОПРОВЕРКОЙ И ОТКАТОМ.
#
# Зачем откат. Сервер стоит в РАЗРЫВЕ DNS всего дома, и выкат идёт на
# одиннадцать клиентов сразу. Не поднимется — у клиента нет интернета вовсе, и
# чинить некому. Худший исход обязан быть «ничего не изменилось», а не «нет
# интернета».
#
# Поэтому порядок жёсткий и обратный на каждом шаге:
#   1. отказ ДО единой записи, если что-то не так (места нет, чужой заворот,
#      файл не тот);
#   2. копии прежнего состояния СНИМАЮТСЯ ДО поломки и проверяются размером
#      (правило 37);
#   3. запуск и ПРОВЕРКА ОТВЕТОМ — не «процесс жив», а «служба ответила»;
#   4. не ответила за названный срок — полный возврат и внятный текст, ПОЧЕМУ.
#
# Названное число: сервер обязан ответить за WAIT секунд (по умолчанию 20).

set -u
BIN=/opt/bin/meridian-dns
INIT=/opt/etc/init.d/S81meridian-dns
CONF=/opt/etc/qwdtt/meridian-dns.yaml
BAKDIR=/opt/var/backup/qwdtt
CRONFILE=/opt/etc/crontabs/root
RUNDIR=/opt/var/run
# След автоотката — ОТДЕЛЬНЫЙ файл рядом с конфигом, по той же схеме, что
# last_rollback у движка. Не в /opt/var/run: там tmpfs у части прошивок, и след
# исчезал бы при перезагрузке — то есть ровно тогда, когда он нужнее всего.
ROLLBACKMARK=/opt/etc/qwdtt/meridian-dns.rollback
CRONMARK="meridian-dns ensure"
WAIT="${WAIT:-20}"
NEWBIN="${1:-}"
NEWINIT="${2:-}"
NEWHOOK="${3:-}"
HOOK=/opt/etc/ndm/netfilter.d/50-meridian-dns.sh

say() { echo "[meridian-dns] $*"; }
die() { echo "[meridian-dns] ОТКАЗ: $*" >&2; exit 1; }

# die_kod — отказ СО СВОИМ КОДОМ. Заведён 07.09.2026 по запросу КОТА 2: он по
# коду решает, ставить ли наши пакеты ipset, а оба случая отдавали 1, и
# различить их можно было только разбором текста. Текст — человеку, код —
# машине (правило 27); два разных исхода с разным лечением обязаны иметь разные
# коды, иначе панель гадает.
#
#   7 — утилиты ipset НЕТ. Лечится установкой наших пакетов.
#   8 — утилита ЕСТЬ, наборы не работают. Пакеты НЕ помогут: дело в ядре или
#       правах, и ставить их поверх значит лечить не то.
die_kod() { _k="$1"; shift; echo "[meridian-dns] ОТКАЗ: $*" >&2; exit "$_k"; }

[ -n "$NEWBIN" ] || die "usage: $0 <новый-бинарь> [<новый-init>] [<крючок-netfilter.d>]"
[ -f "$NEWBIN" ] || die "нет файла $NEWBIN"

# ---------- 0. ДВИЖОК МАРШРУТИЗАЦИИ — МИНИМАЛЬНАЯ ВЕРСИЯ ----------
# meridian-dns-init.sh зовёт `meridian-route home-ifaces` на каждом старте
# (список мостов дома, белый режим гостевой br1) — команда появилась в
# движке 1.69. На более старом движке (живой случай 23.09.2026: тестировщик
# застрял на 1.38, оставшемся от утечки) meridian-route отвечает "неизвестная
# команда", meridian-dns не стартует, meridian-dns-init.sh откатывает на
# прежний DNS — сам по себе откат сработал верно, но ДО него зря снесли
# работавший DNS и потратили время тестировщика на разбор чужого текста
# ошибки. Проверяем версию ДО единой записи и ДО остановки текущего DNS:
# нет — говорим прямо, что нужно, ничего не трогаем.
MERIDIAN_ROUTE_BIN=/opt/bin/meridian-route
MERIDIAN_ROUTE_MIN_MAJOR=1
MERIDIAN_ROUTE_MIN_MINOR=69
if [ -x "$MERIDIAN_ROUTE_BIN" ]; then
    _mr_ver=$("$MERIDIAN_ROUTE_BIN" version 2>&1 | head -1 | grep -oE '[0-9]+\.[0-9]+' | head -1)
    if [ -n "$_mr_ver" ]; then
        _mr_major=${_mr_ver%.*}
        _mr_minor=${_mr_ver#*.}
        case "$_mr_major" in ''|*[!0-9]*) _mr_major=0 ;; esac
        case "$_mr_minor" in ''|*[!0-9]*) _mr_minor=0 ;; esac
        if [ "$_mr_major" -lt "$MERIDIAN_ROUTE_MIN_MAJOR" ] || \
           { [ "$_mr_major" -eq "$MERIDIAN_ROUTE_MIN_MAJOR" ] && [ "$_mr_minor" -lt "$MERIDIAN_ROUTE_MIN_MINOR" ]; }; then
            die "движок $_mr_ver слишком старый, нужен ≥$MERIDIAN_ROUTE_MIN_MAJOR.$MERIDIAN_ROUTE_MIN_MINOR — поставь полный набор беты: curl -sf http://10.77.77.1:8080/beta/install.sh -o /tmp/install.sh && sh /tmp/install.sh (текущий DNS не трогал)"
        fi
    else
        say "не разобрал версию $MERIDIAN_ROUTE_BIN (вывод: $("$MERIDIAN_ROUTE_BIN" version 2>&1 | head -1)) — проверку версии движка пропускаю, не отказываю вслепую"
    fi
else
    say "$MERIDIAN_ROUTE_BIN не найден — сборка без движка маршрутизации, проверка версии тут ни при чём"
fi

# ---------- 1. ОТКАЗ ДО ЕДИНОЙ ЗАПИСИ ----------

say "проверки до записи"

# 1.1 файл — тот, что мы думаем
head -c 4 "$NEWBIN" | grep -q 'ELF' || die "$NEWBIN не ELF"
if command -v file >/dev/null 2>&1; then
    file -b "$NEWBIN" | grep -q 'statically linked' \
        || die "$NEWBIN динамически слинкован — на роутере он не запустится (28.08 так легла служба в Беларуси)"
fi
"$NEWBIN" version >/dev/null 2>&1 || die "$NEWBIN не запускается на этом железе"
say "  файл: ELF, статический, запускается"

# 1.1а ЗАВИСИМОСТИ. ДО ЕДИНОЙ ЗАПИСИ НА ДИСК.
#
# 07.09.2026, ТРЕТИЙ отказ установки у одного человека. На его роутере утилиты
# ipset нет физически, а ядро наши наборы поддерживает. Комплект звал ipset как
# внешнюю команду и НИ РАЗУ не проверял, что она есть: установщик доходил до
# запуска сервера, сервер молча не мог создать набор, и мы узнавали об этом по
# косвенным признакам. Три захода к живому человеку ушли на то, что установщик
# мог сказать первой строкой.
#
# ПРОВЕРЯЕМ ДЕЛОМ, А НЕ НАЛИЧИЕМ. Файл может быть, а модуль ядра не собран;
# может быть сборка без hash:net; может не хватать прав. Снаружи все эти случаи
# выглядят одинаково — «набор не создался».
#
# ПРОБА В ОБЕ СТОРОНЫ. Попадание И ПРОМАХ: набор, который отвечает «да» на что
# угодно, завернул бы в туннель весь трафик дома, а проверка одного попадания
# на нём зелена (правило 25: проверять обе стороны).
IPSET_BIN=$(command -v ipset 2>/dev/null)
if [ -z "$IPSET_BIN" ]; then
    for _p in /opt/sbin/ipset /usr/sbin/ipset /sbin/ipset; do
        if [ -x "$_p" ]; then IPSET_BIN="$_p"; break; fi
    done
fi
if [ -z "$IPSET_BIN" ]; then
    die_kod 7 "утилиты ipset на этом роутере НЕТ. Без неё сервер не создаст ни одного набора и в туннель не пойдёт НИЧЕГО. Поставьте её и повторите: opkg update && opkg install ipset (проверить: ipset --version)"
fi
say "  ipset: $IPSET_BIN"

# Имя пробного набора с PID: два одновременных запуска не помешают друг другу.
DEPSET="md_dep_$$"
"$IPSET_BIN" destroy "$DEPSET" >/dev/null 2>&1
DEPERR=$("$IPSET_BIN" create "$DEPSET" hash:net family inet 2>&1)
if [ "$?" != 0 ]; then
    die_kod 8 "ipset есть ($IPSET_BIN), но набор hash:net не создаётся: $DEPERR. Утилита на месте — значит дело в ядре или правах. Проверьте руками: ipset create проба hash:net family inet"
fi
DEPERR=$("$IPSET_BIN" add "$DEPSET" 198.51.100.0/24 2>&1)
if [ "$?" != 0 ]; then
    "$IPSET_BIN" destroy "$DEPSET" >/dev/null 2>&1
    die_kod 8 "набор создан, но подсеть в него не кладётся: $DEPERR"
fi
if ! "$IPSET_BIN" test "$DEPSET" 198.51.100.7 >/dev/null 2>&1; then
    "$IPSET_BIN" destroy "$DEPSET" >/dev/null 2>&1
    die_kod 8 "набор создан и заполнен, но попадание не видно: 198.51.100.7 обязан лежать в 198.51.100.0/24. Наборы на этом ядре не работают"
fi
if "$IPSET_BIN" test "$DEPSET" 203.0.113.7 >/dev/null 2>&1; then
    "$IPSET_BIN" destroy "$DEPSET" >/dev/null 2>&1
    die_kod 8 "набор говорит, что 203.0.113.7 лежит в 198.51.100.0/24 — совпадает всё подряд. Ставить нельзя: в туннель ушёл бы весь трафик дома"
fi
"$IPSET_BIN" destroy "$DEPSET" >/dev/null 2>&1
# УНИЧТОЖЕНИЕ ПРОВЕРЯЕМ ЧТЕНИЕМ, а не кодом возврата destroy (правило 37).
if "$IPSET_BIN" list "$DEPSET" >/dev/null 2>&1; then
    die_kod 8 "пробный набор $DEPSET не уничтожается — снимите его руками: ipset destroy $DEPSET"
fi
say "  наборы: создать, положить, попадание, промах, уничтожить — всё работает"

# Матч set у iptables: без него метка не поставится, сколько бы наборов мы ни
# создали. ТРИ исхода, а не два: есть / нет / не смогли посмотреть.
MATCHES=/proc/net/ip_tables_matches
if [ ! -r "$MATCHES" ]; then
    say "  матч set: НЕ СМОГЛИ ПОСМОТРЕТЬ ($MATCHES не читается) — это не «есть» и не «нет»"
else
    SETMATCH=$(grep -c '^set$' "$MATCHES" 2>/dev/null)
    if [ "${SETMATCH:-0}" = 0 ]; then
        die "у iptables нет матча set (в $MATCHES ни одной строки «set»). Наборы создать удастся, а пометить по ним трафик — нет. Обычно помогает: opkg install iptables-mod-ipset"
    fi
    say "  матч set у iptables: есть ($SETMATCH строк в $MATCHES)"
fi

# 1.2 чужой заворот DNS
# Признаки конкурента — те же, что в коде сервера (isForeignDivertLine):
# цепочка не наша и не прошивочная (_NDM_*), и увод на порт, отличный от 53.
# Прошивочный REDIRECT --to-ports 53 конкурентом НЕ является: это наш же
# запасной путь, и он есть на каждом Keenetic.
FOREIGN=$(iptables -t nat -S 2>/dev/null | awk '
    /--dport 53/ && (/-j DNAT/ || /-j REDIRECT/) && !/_NDM_/ && !/MERIDIAN_DNS/ {
        port = ""
        for (i = 1; i <= NF; i++)
            if ($i == "--to-destination" || $i == "--to-ports") {
                port = $(i+1)
                sub(/.*:/, "", port)
            }
        if (port != "53") { print; exit }
    }')
if [ -n "$FOREIGN" ]; then
    echo "[meridian-dns] ОТКАЗ: в nat уже стоит чужой заворот DNS." >&2
    echo "    $FOREIGN" >&2
    echo "    Два перехватчика на одном потоке не сосуществуют: чей заворот раньше," >&2
    echo "    тот и получает запросы, второй пишет в отчёт ноль и выглядит сломанным." >&2
    echo "    Остановите чужой (например: /opt/etc/init.d/S99magitrickle stop) и повторите." >&2
    exit 1
fi
say "  чужого заворота DNS нет"

# 1.2б Порт. Отдельной проверкой и ДО единой записи: 04.09.2026 порт 53535
# оказался внутри эфемерного диапазона ядра и был занят ndnproxy. Узнавать это
# откатом по таймауту через 20 секунд — расточительство: причина известна сразу.
# Умолчание — auto: адрес выводит сам бинарь из интерфейса (см. lanaddr.go).
# Зашитое здесь 192.168.1.1 было ВТОРОЙ копией адреса роутера владельца; копии
# в двух скриптах разошлись бы, как разошлись двери у метки времени.
LISTEN_PRE="${MERIDIAN_DNS_LISTEN:-auto:5453}"
IFACES_PRE="${MERIDIAN_DNS_IFACES:-br0}"
[ -f /opt/etc/qwdtt/meridian-dns.env ] && . /opt/etc/qwdtt/meridian-dns.env 2>/dev/null
LISTEN_PRE="${MERIDIAN_DNS_LISTEN:-$LISTEN_PRE}"
# -ifaces ОБЯЗАТЕЛЕН РЯДОМ С auto, и это не мелочь.
#
# Умолчание -ifaces в бинаре — br0. Предпроверка звалась без него, а init
# передаёт своё значение: на роутере с другим именем моста (OpenWRT обычно
# br-lan) установка отказывала бы там, где сервер потом встал бы прекрасно.
# Третья дверь того же расхождения за один день — поймано стендом 06.09.2026.
IFACES_PRE="${MERIDIAN_DNS_IFACES:-$IFACES_PRE}"
# Код 3 — порт держит НАШ ЖЕ работающий сервер. Это не препятствие: мы его
# сейчас и остановим, это часть установки. 04.09.2026 версия 0.2 не встала
# именно здесь («порт 5453 занят meridian-dns (pid 10851)»), а на парке это
# означало бы, что новая версия не раскатывается вообще ни на один роутер.
"$NEWBIN" -listen "$LISTEN_PRE" -ifaces "$IFACES_PRE" -pid "$RUNDIR/meridian-dns.pid" checkport
RCPORT=$?
if [ "$RCPORT" = 3 ]; then
    say "  порт держит наш же сервер — остановлю его при установке"
elif [ "$RCPORT" != 0 ]; then
    die "порт непригоден (см. строку выше). Смените MERIDIAN_DNS_LISTEN в /opt/etc/qwdtt/meridian-dns.env"
fi

# 1.3 место — ЗАМЕРОМ, а не по номиналу.
#
# Номинальный размер на UBIFS неверен: файловая система сжимает сама, и бинарь
# 3,9 МБ занимает около 1,4 МБ. 04.09.2026 проверка по номиналу сорвала
# установку («нужно 7936 КБ, свободно 7072») там, где места хватало вдвое.
#
# Меряем тем же способом, каким и ставим: пишем файл во временное имя НА
# ЦЕЛЕВОМ РАЗДЕЛЕ и смотрим df до и после. Это разом проверка места и проверка
# ЗАПИСИ — а результат записи смотреть обязательно (правило 19: 17.08 ноль лёг
# поверх работающей панели именно потому, что считали скачанные байты, а не
# записанные).
FREE_BEFORE=$(df -k /opt 2>/dev/null | awk 'NR==2{print $4}')
case "$FREE_BEFORE" in ''|*[!0-9]*) FREE_BEFORE=0 ;; esac
if ! cp "$NEWBIN" "$BIN.incoming" 2>/dev/null; then
    rm -f "$BIN.incoming"
    die "не записать $BIN.incoming — вероятно, не хватило места (свободно ${FREE_BEFORE} КБ)"
fi
sync 2>/dev/null
if [ "$(wc -c < "$BIN.incoming")" != "$(wc -c < "$NEWBIN")" ]; then
    GOT=$(wc -c < "$BIN.incoming"); rm -f "$BIN.incoming"
    die "записалось не полностью: $GOT из $(wc -c < "$NEWBIN") байт — не хватило места (свободно ${FREE_BEFORE} КБ)"
fi
FREE_AFTER=$(df -k /opt 2>/dev/null | awk 'NR==2{print $4}')
case "$FREE_AFTER" in ''|*[!0-9]*) FREE_AFTER=0 ;; esac
REALLY=$(( FREE_BEFORE - FREE_AFTER ))
[ "$REALLY" -lt 0 ] && REALLY=0
say "  место: номинал $(( $(wc -c < "$NEWBIN") / 1024 )) КБ, на диске занял ${REALLY} КБ, осталось ${FREE_AFTER} КБ"
# Бэкап — копия ПРЕЖНЕГО бинаря; на первой установке его нет и место не нужно.
#
# СЧИТАЕМ РАЗНИЦУ, А НЕ ПОЛНЫЙ РАЗМЕР. 08.09.2026 отказ заблокировал ВТОРУЮ
# установку на роутере владельца: копия .prev там уже лежала с утренней
# установки (7 995 585 Б), мы её ПЕРЕЗАПИСЫВАЕМ — значит сверху нужна разница
# между прежним бинарём и тем, что уже занято копией, а не весь размер в
# пустоту. Разница почти ноль, а требовали 7872 КБ.
#
# max(0, …) обязателен: если прежний бинарь МЕНЬШЕ лежащей копии, перезапись
# место освободит, и отрицательная потребность означала бы ноль, а не «минус».
if [ -f "$BIN" ]; then
    NUZHNO=$(wc -c < "$BIN")
    UZHE=0
    if [ -f "$BAKDIR/meridian-dns.prev" ]; then
        UZHE=$(wc -c < "$BAKDIR/meridian-dns.prev")
    fi
    RAZNICA=$(( NUZHNO - UZHE ))
    if [ "$RAZNICA" -lt 0 ]; then
        RAZNICA=0
    fi
    NEEDBAK=$(( RAZNICA / 1024 ))
    if [ "$UZHE" != 0 ]; then
        say "  бэкап: копия уже лежит ($(( UZHE / 1024 )) КБ), перезапись требует ещё ${NEEDBAK} КБ"
    fi
    if [ "$FREE_AFTER" -lt "$NEEDBAK" ]; then
        rm -f "$BIN.incoming"
        OSVOB=$(df -k /opt 2>/dev/null | awk 'NR==2{print $4}')
        case "$OSVOB" in ''|*[!0-9]*) OSVOB=0 ;; esac
        # ЧИСЛОМ, А НЕ СЛОВОМ «откатился». Снятый огрызок обязан быть виден.
        say "  огрызок $BIN.incoming снят, после отката свободно ${OSVOB} КБ"
        die "на перезапись бэкапа нужно ещё ~${NEEDBAK} КБ (прежний бинарь $(( NUZHNO / 1024 )) КБ, уже занято копией $(( UZHE / 1024 )) КБ), свободно ${FREE_AFTER} КБ"
    fi
fi

# ---------- 2. КОПИИ ДО ПОЛОМКИ ----------

mkdir -p "$BAKDIR" 2>/dev/null || die "не создать $BAKDIR"
HADBIN=0; HADINIT=0; HADCRON=0
if [ -f "$BIN" ]; then
    cp -p "$BIN" "$BAKDIR/meridian-dns.prev" || die "не снять копию $BIN"
    [ "$(wc -c < "$BAKDIR/meridian-dns.prev")" = "$(wc -c < "$BIN")" ] \
        || die "копия $BIN не совпала размером — установка не начинается"
    HADBIN=1
fi
if [ -f "$INIT" ]; then
    cp -p "$INIT" "$BAKDIR/meridian-dns-init.prev" || die "не снять копию $INIT"
    # СВЕРКА СОДЕРЖИМЫМ, как у бинаря выше. Здесь её не было: копия бинаря
    # проверялась размером, а копия init — только кодом возврата cp. Копия, о
    # которой мы знаем лишь «cp вернул ноль», — это не откат, а надежда на него
    # (правило 37).
    [ "$(wc -c < "$BAKDIR/meridian-dns-init.prev")" = "$(wc -c < "$INIT")" ] \
        || die "копия $INIT не совпала размером — установка не начинается"
    HADINIT=1
fi
if grep -qF "$CRONMARK" "$CRONFILE" 2>/dev/null; then HADCRON=1; fi
say "копии сняты (был бинарь: $HADBIN, init: $HADINIT, периодика: $HADCRON)"

# rb_chelovek — ЧИТАЕМАЯ дата следа отката.
#
# Голая метка «1788542172» человеку не говорит ничего, а строка существует
# ровно для человека. Дефект записан 04.09.2026 и это его третий экземпляр
# подряд — поэтому перевод стоит в ОБОИХ местах, где след показывают
# (здесь и `rollback-ack` в init-скрипте), и оба закрыты стендом. Сторож у
# одной двери из двух не сторож (правило 43).
#
# at_human пишет сам установщик (с 0.3), и он ВЕРНЕЕ перевода задним числом:
# часовой пояс роутера мог смениться между откатом и показом.
#
# Способ перевода ВЫБИРАЕТСЯ ПРОБОЙ, а не предполагается: `date -d @N` есть в
# GNU и в части сборок BusyBox, `date -D %s -d N` — busybox-специфичный, и
# обеих форм на роутере может не быть (правило 25). Не вышло ни одной — так и
# говорим, а не печатаем пустоту, которую примут за дату.
rb_chelovek() {
    _w=$(sed -n 's/^at_human=//p' "$ROLLBACKMARK" 2>/dev/null | head -1)
    if [ -n "$_w" ]; then
        echo "$_w"
        return 0
    fi
    _t=$(sed -n 's/^at=//p' "$ROLLBACKMARK" 2>/dev/null | head -1)
    case "$_t" in ''|*[!0-9]*) echo "время в следе не записано"; return 0 ;; esac
    _h=$(date -d "@$_t" '+%Y-%m-%d %H:%M:%S' 2>/dev/null)   # bb-ok: результат проверяется, есть запасные пути
    if [ -n "$_h" ]; then
        echo "$_h"
        return 0
    fi
    _h=$(date -D %s -d "$_t" '+%Y-%m-%d %H:%M:%S' 2>/dev/null)   # bb-ok: то же
    if [ -n "$_h" ]; then
        echo "$_h"
        return 0
    fi
    echo "date этой сборки метку $_t не переводит"
}

rollback() {
    WHY="$1"
    rm -f "$BIN.incoming" 2>/dev/null
    echo "[meridian-dns] ОТКАТ: $WHY" >&2
    # След ставим ПЕРВЫМ делом: если дальше что-то пойдёт не так, человек всё
    # равно узнает, что откат был и почему.
    mkdir -p "$(dirname "$ROLLBACKMARK")" 2>/dev/null
    { echo "at=$(date +%s)"
      echo "at_human=$(date '+%Y-%m-%d %H:%M:%S')"
      echo "reason=selfcheck_failed"
      echo "effect=previous_version_restored"
      echo "note=$WHY"
    } > "$ROLLBACKMARK.tmp" 2>/dev/null && mv -f "$ROLLBACKMARK.tmp" "$ROLLBACKMARK" 2>/dev/null
    [ -x "$INIT" ] && "$INIT" stop >/dev/null 2>&1
    "$BIN" off >/dev/null 2>&1
    if [ "$HADBIN" = 1 ]; then
        cp -p "$BAKDIR/meridian-dns.prev" "$BIN.restore" && mv -f "$BIN.restore" "$BIN"
        # СВЕРКА СОДЕРЖИМЫМ, а не кодом возврата cp (правило 37).
        if cmp -s "$BAKDIR/meridian-dns.prev" "$BIN"; then
            echo "[meridian-dns] прежний бинарь возвращён" >&2
        else
            echo "[meridian-dns] ВНИМАНИЕ: прежний бинарь ВЕРНУТЬ НЕ УДАЛОСЬ. Вручную:" >&2
            echo "    cp -p $BAKDIR/meridian-dns.prev $BIN" >&2
        fi
    else
        rm -f "$BIN"
        echo "[meridian-dns] бинаря не было — удалён" >&2
    fi
    if [ "$HADINIT" = 1 ]; then
        cp -p "$BAKDIR/meridian-dns-init.prev" "$INIT.restore" && mv -f "$INIT.restore" "$INIT"
    else
        rm -f "$INIT"
    fi
    if [ "$HADCRON" = 0 ] && [ -f "$CRONFILE" ]; then
        grep -vF "$CRONMARK" "$CRONFILE" > "$CRONFILE.tmp" 2>/dev/null
        mv -f "$CRONFILE.tmp" "$CRONFILE" 2>/dev/null
    fi
    if [ "$HADBIN" = 1 ] && [ "$HADINIT" = 1 ]; then
        "$INIT" start >/dev/null 2>&1 && echo "[meridian-dns] прежняя версия запущена" >&2
    fi
    echo "[meridian-dns] состояние возвращено к прежнему. Интернет в доме работает как до установки." >&2
    exit 1
}

# ---------- 3. УСТАНОВКА ----------

# INIT-СКРИПТ — ПЕРВЫМ, ДО ОСТАНОВКИ. 22.09.2026, живой случай HERO: старый
# init.sh (тот, что ещё лежит на диске в момент stop) умеет гасить ТОЛЬКО
# записанного в pid-файле guard'а — если сторож на этот момент оказался
# запущен ДРУГИМ путём (periodika/ensure), он сиротой переживает stop. Новый
# init.sh это чинит (гасит ВСЕХ guard по /proc), но чинит только если он уже
# на диске В МОМЕНТ вызова stop — то есть до, а не после. $NEWINIT уже
# скачан и сверен по сумме ДО вызова этого установщика (ustanovka-dns.sh),
# трогать текущий процесс это никак не может — swap файла скрипта не влияет
# на уже запущенные процессы, только на СЛЕДУЮЩИЙ вызов $INIT.
if [ -n "$NEWINIT" ] && [ -f "$NEWINIT" ]; then
    cp "$NEWINIT" "$INIT.incoming" && chmod +x "$INIT.incoming" && mv -f "$INIT.incoming" "$INIT" \
        || die "не удалось положить init-скрипт — ничего ещё не остановлено, роутер как был"
fi
[ -x "$INIT" ] && "$INIT" stop >/dev/null 2>&1
# ПЕРЕПРОВЕРКА ПОСЛЕ ОСТАНОВКИ. «Остановили» и «порт освободился» — разные
# утверждения: процесс мог не умереть, и тогда новый не поднимется, а мы
# узнаем об этом только откатом по таймауту через 20 секунд.
if [ -x "$BIN" ]; then
    "$BIN" -listen "$LISTEN_PRE" -ifaces "$IFACES_PRE" -pid "$RUNDIR/meridian-dns.pid" checkport >/dev/null 2>&1
    RCPORT2=$?
    if [ "$RCPORT2" != 0 ]; then
        rm -f "$BIN.incoming" 2>/dev/null
        "$BIN" -listen "$LISTEN_PRE" -ifaces "$IFACES_PRE" -pid "$RUNDIR/meridian-dns.pid" checkport
        die "порт не освободился после остановки прежнего сервера. Ничего не менял."
    fi
fi
# $BIN.incoming уже записан и сверен на шаге 1.3 — второй раз не пишем.
[ -f "$BIN.incoming" ] || die "временный файл пропал между проверкой и установкой"
chmod +x "$BIN.incoming"
mv -f "$BIN.incoming" "$BIN" || die "не подменить $BIN"
# КРЮЧОК ndm. Ставится третьим файлом, если его передали. Без него заворот
# возвращает только периодика — не позже чем через минуту, и минуту дом
# резолвит мимо нас. 04.09.2026 заворот пропадал дважды за вечер.
if [ -n "$NEWHOOK" ] && [ -f "$NEWHOOK" ]; then
    if [ -d "$(dirname "$HOOK")" ]; then
        cp "$NEWHOOK" "$HOOK.incoming" && chmod +x "$HOOK.incoming" && mv -f "$HOOK.incoming" "$HOOK" \
            || rollback "не удалось положить крючок netfilter.d"
        say "  крючок ndm: $HOOK"
    else
        # Каталога нет — значит прошивка крючки не зовёт. Молчать нельзя:
        # человек будет думать, что окно сокращено, а оно прежнее.
        say "  ВНИМАНИЕ: $(dirname "$HOOK") нет — крючок НЕ поставлен, заворот возвращает только периодика (до минуты)"
    fi
fi
say "файлы на месте"

# КОНФИГА НЕТ — ЗАВОДИМ ПУСТОЙ, А НЕ ОТКАТЫВАЕМСЯ.
#
# Владелец задал порядок: сначала установка, потом загрузка списка
# (`import-list`). Прежний отказ этот порядок ломал: установщик требовал
# конфиг, а конфиг создаёт как раз import-list — то есть первый шаг был
# невозможен без второго, а второй без первого.
#
# Пустой конфиг — законное состояние: проверено поведением 06.09.2026, сервер
# на нём поднимается, отвечает на пробу и честно пишет «помечать нечего».
# Это лучше отката: служба стоит, заворот на месте, и человеку остаётся один
# шаг вместо переустановки.
#
# Прежнее сообщение вдобавок посылало к импорту из MagiTrickle, который с
# критического пути снят.
# ОДНА ДВЕРЬ НА СОЗДАНИЕ ПУСТОГО КОНФИГА (правило 51). Мест, где он заводится,
# стало два — «его не было» и «прежний отложен», — и копия кода в каждом из них
# разъехалась бы молча.
sozdat_pustoj_konfig() {
    mkdir -p "$(dirname "$CONF")" 2>/dev/null
    printf 'version: 1\nsetPrefix: md_\ngroups: []\n' > "$CONF.incoming" 2>/dev/null \
        || rollback "не удалось создать $CONF (нет места или прав)"
    mv -f "$CONF.incoming" "$CONF" 2>/dev/null || rollback "не удалось положить $CONF"
    # СВЕРКА СОДЕРЖИМЫМ, а не кодом возврата mv (правило 37).
    grep -q '^groups: \[\]$' "$CONF" 2>/dev/null || rollback "$CONF создан, но содержимое не то"
    say "  список правил загрузите после установки:"
    say "    $BIN import-list <файл> --group \"Обход\" --mode black"
    say "  до этого сервер работает, но НИЧЕГО не помечает — в туннель не идёт ничего"
}

if [ ! -f "$CONF" ]; then
    say "конфига не было — создан ПУСТОЙ: $CONF"
    sozdat_pustoj_konfig
else
    # КОНФИГ УЖЕ ЕСТЬ — ГОВОРИМ ОБ ЭТОМ И НАЗЫВАЕМ, ЧТО В НЁМ.
    #
    # 07.09.2026, условие владельца третье. До этой правки существующий конфиг
    # брался молча: ни строки о том, что он есть, ни о том, что в нём. У клиента
    # там лежал ОСИРОТЕВШИЙ конфиг от неудачной попытки 06.09 — то есть «чистая
    # установка» шла без бинаря, но с чужим конфигом неизвестного возраста.
    # Молчание было прочитано как «конфига нет», и разбор пошёл не туда.
    #
    # МОЛЧАНИЕ НЕ ДОЛЖНО ЗНАЧИТЬ «НИЧЕГО НЕТ».
    say "конфиг УЖЕ ЕСТЬ: $CONF — он лежал ДО этой установки, мы его не создавали"
    CFG_OUT=$("$BIN" -config "$CONF" check-config 2>&1)
    CFG_RC=$?
    printf '%s\n' "$CFG_OUT" | sed 's/^/[meridian-dns]   /'
    # НИ ОДНОГО ПРАВИЛА НЕ ЧИТАЕТСЯ — ОТКЛАДЫВАЕМ И СТАВИМ, А НЕ ОТКАЗЫВАЕМ.
    #
    # Решение владельца 07.09.2026, и довод его: конфиг meridian-dns.yaml на
    # роутере, где нашего сервера НИКОГДА не было, — это наш мусор от неудачного
    # захода, а не данные человека. Ничьих данных в нём нет по определению.
    #
    # Прежняя редакция здесь отказывала, и клиент, которому мы уже дважды не
    # поставили, получил бы ТРЕТИЙ отказ подряд — из-за файла, который оставили
    # мы сами.
    #
    # Код 2 («не прочитать вовсе») лечится так же и по той же причине: правил из
    # него не читается тоже ни одного. Это моё решение внутри вашего довода, и
    # я его называю: отличать «не разобрать» от «разобрали, но всё негодное»
    # человеку здесь не для чего, а отказ стоил бы ему установки.
    #
    # НИЧЕГО НЕ ТЕРЯЕТСЯ: прежний файл остаётся на диске под .was.
    if [ "$CFG_RC" = 1 ] || [ "$CFG_RC" = 2 ]; then
        say "НАЙДЕН ПРЕЖНИЙ КОНФИГ, ИЗ КОТОРОГО НЕ ЧИТАЕТСЯ НИ ОДНО ПРАВИЛО (код $CFG_RC)"
        say "  что в нём было — напечатано выше: числа и негодные строки поимённо"
        mv -f "$CONF" "$CONF.was" 2>/dev/null \
            || rollback "прежний конфиг $CONF не отложить в $CONF.was (нет прав или места) — ставить поверх него нельзя"
        # СВЕРКА СОДЕРЖИМЫМ, а не кодом возврата mv (правило 37): «отложен» это
        # «его там нет И он есть здесь», а не «mv вернул ноль».
        [ -f "$CONF.was" ] || rollback "после переноса $CONF.was не появился — прежний конфиг потерян, установка остановлена"
        # ВТОРОЙ ПРОВЕРКИ («$CONF всё ещё на месте») здесь НЕТ намеренно.
        # Она стояла и была снята 07.09.2026: ни один случай не делает её
        # красной отдельно от первой — mv либо переносит, либо отказывает, и
        # источник остаться не может. Проверка, для которой не придумывается
        # своя мутация, — это описание, а не проверка, и рядом с настоящей она
        # создаёт впечатление двойной защиты (правила 36 и 49).
        say "  прежний ОТЛОЖЕН в $CONF.was — он остаётся на диске, ничего не потеряно"
        say "  ставим С ЧИСТОГО: создан ПУСТОЙ $CONF"
        sozdat_pustoj_konfig
    fi
fi

# ЧТО ПРОИСХОДИТ С ДЕМОНОМ — ПОКАЗЫВАЕМ, А НЕ ГЛОТАЕМ.
#
# 07.09.2026, чистая установка на роутере клиента. Вывод init уходил в
# /dev/null, и отказ выглядел так: «файлы на месте» → «сервер НЕ ответил за
# 20 с» → откат. По этой строке НЕЛЬЗЯ отличить четыре разные причины:
#   1) сервер не запустился вовсе;
#   2) запустился и сразу вышел (чужой заворот в nat, занятый порт, битый
#      конфиг) — ровно это и случилось у клиента;
#   3) запустился, но слушает не тот адрес;
#   4) слушает верный адрес, но не отвечает.
# Различает их ОДНА строка в журнале сервера, и мы её просто выбрасывали.
INIT_OUT=$("$INIT" start 2>&1)
INIT_RC=$?
say "init start: код $INIT_RC"
if [ -n "$INIT_OUT" ]; then
    printf '%s\n' "$INIT_OUT" | sed 's/^/[meridian-dns]   /' >&2
fi
# Журнал сервера — ПОСЛЕДНИЕ строки, и с числом. Пустой журнал это не «всё
# хорошо», это «мы ничего не увидели», и сказать надо именно так.
sleep 2
# ПУТЬ К ЖУРНАЛУ БЕРЁМ ИЗ САМОГО INIT-СКРИПТА, а не пишем второй копией.
#
# Копия пути рядом с оригиналом разъезжается молча — сегодня это уже стоило нам
# listen-file. init знает, куда он направляет вывод сервера; спрашиваем его.
SRVLOG=$(sed -n 's/^LOG=//p' "$INIT" 2>/dev/null | head -1)
if [ -z "$SRVLOG" ]; then
    SRVLOG=/opt/var/log/meridian-dns.log
    say "путь к журналу в $INIT не найден — беру $SRVLOG (это догадка, а не факт)"
fi
LOGSTROK=$(grep -c . "$SRVLOG" 2>/dev/null)
say "журнал сервера $SRVLOG: строк ${LOGSTROK:-0}"
if [ "${LOGSTROK:-0}" = 0 ]; then
    say "  ЖУРНАЛ ПУСТ ИЛИ НЕ ЧИТАЕТСЯ — это не «сервер молчит», это «мы не видим»"
else
    tail -12 "$SRVLOG" 2>/dev/null | sed 's/^/[meridian-dns]   /' >&2
fi
if [ "$INIT_RC" != 0 ]; then
    rollback "init-скрипт не запустился (код $INIT_RC, вывод и журнал выше)"
fi

# ---------- 4. САМОПРОВЕРКА ОТВЕТОМ ----------

# Адрес берём ТОТ, НА КОТОРОМ СЕРВЕР ПОДНЯЛСЯ, а не выводим заново из
# умолчаний. Вывод «наверное такой же» — это не проверка, а совпадение: на
# стенде probe спрашивал 127.0.0.1:53535, пока сервер слушал 192.168.1.1:53535,
# и установка откатывалась ВСЕГДА.
LISTEN=$(cat "$RUNDIR/meridian-dns.listen" 2>/dev/null)
# ФАЙЛ ОБЯЗАН СОДЕРЖАТЬ АДРЕС, А НЕ НАСТРОЙКУ.
#
# 07.09.2026 у клиента здесь лежало «auto:5453»: init прежней версии писал в
# файл настроенное значение. Отказ выглядел как «сервер не ответил», хотя
# сервер был ни при чём. Проверяем ВИД строки, а не только непустоту.
case "${LISTEN:-}" in
    [0-9]*.[0-9]*.[0-9]*.[0-9]*:[0-9]*) : ;;
    "") rollback "адрес, на котором слушает сервер, не назван ($RUNDIR/meridian-dns.listen пуст)" ;;
    *)  rollback "в $RUNDIR/meridian-dns.listen лежит «$LISTEN» — это не адрес вида X.X.X.X:порт, а настройка. Опрашивать по ней нечего" ;;
esac
say "жду ответа сервера на $LISTEN, до ${WAIT} с"
if "$BIN" -listen "$LISTEN" -probe-wait "${WAIT}s" probe; then
    say "сервер ответил"
else
    # ПРИЧИНА — ИЗ ЖУРНАЛА СЕРВЕРА, а не догадкой. «Не ответил» это следствие,
    # и по нему одному нельзя отличить «сел не туда» от «не сел вовсе».
    say "сервер не ответил. Последнее, что он написал:"
    if [ -s "$SRVLOG" ]; then
        tail -15 "$SRVLOG" 2>/dev/null | sed 's/^/[meridian-dns]   /' >&2
    else
        say "  журнал $SRVLOG пуст или не читается — значит сервер не дошёл даже до первой строки"
    fi
    rollback "сервер не ответил за ${WAIT} с — причина в строках выше"
fi

# Заворот обязан стоять: сервер отвечает, но если правила нет, дом идёт мимо нас.
if iptables -t nat -C PREROUTING -j MERIDIAN_DNS 2>/dev/null; then
    say "заворот на месте"
else
    rollback "сервер отвечает, но заворот не поставлен — дом шёл бы мимо нас"
fi

# КОПИЯ МОДУЛЯ СНИМАЕТСЯ ПОСЛЕ ТОГО, КАК НОВЫЙ ОТВЕТИЛ.
#
# Замер 13.09.2026: на Keenetic флеш 46 МБ, у владельца свободно оставалось
# 9,6 МБ, а модуль DNS занимал его ДВАЖДЫ — 7,7 МБ боевой и 7,7 МБ копия.
# Шестая часть всего флеша уходила на откат, который и так есть в раздаче под
# боевым именем и качается за секунды.
#
# ПОРЯДОК ВАЖЕН И НЕ МЕНЯЕТСЯ: копия снимается ДО подмены (правило 19 — нет
# годного бэкапа, обновление не начинается вовсе) и удаляется ТОЛЬКО здесь,
# после того как служба ОТВЕТИЛА и заворот проверен. «Процесс жив» для этого
# не годится: именно на таком признаке 17.08 ноль лёг поверх рабочей панели.
#
# init.prev НЕ УДАЛЯЕМ НАМЕРЕННО: он 30 КБ, и откат init-скрипта им не зависит
# от сети. Дорогая копия — только у модуля.
if [ -f "$BAKDIR/meridian-dns.prev" ]; then
    OSVOB=$(wc -c < "$BAKDIR/meridian-dns.prev" 2>/dev/null || echo 0)
    if rm -f "$BAKDIR/meridian-dns.prev"; then
        say "копия модуля снята: сервер ответил, откат по ней больше не нужен (освобождено $OSVOB Б)"
    else
        say "ВНИМАНИЕ: копию $BAKDIR/meridian-dns.prev снять не удалось — место на флеше останется занятым"
    fi
fi

if [ -f "$ROLLBACKMARK" ]; then
    say "ВНИМАНИЕ: на роутере остался след прошлого автоотката от $(rb_chelovek)."
    say "  Он снимается только человеком: $INIT rollback-ack"
fi
# ПЕЧАТАЕМ ТОЛЬКО ТО, ЧТО ВЫПОЛНИТСЯ КАК ЕСТЬ (правило 53). Прежняя строка
# обещала копию модуля, которой после удачной установки больше нет, — совет,
# который не работает, хуже отсутствия совета.
say "УСТАНОВЛЕНО."
