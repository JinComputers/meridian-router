#!/bin/sh
CONF="${QWDTT_CONF:-/opt/etc/qwdtt/qwdtt.conf}"; BIN="${QWDTT_BIN:-/opt/bin/qwdtt}"
LOG="${QWDTT_LOG:-/opt/var/log/qwdtt.log}"; PIDF="${QWDTT_PIDF:-/opt/var/run/qwdtt.pid}"
PENDF="/opt/var/run/qwdtt.pending.pid"
WG="/opt/etc/qwdtt/wg.conf"
TIMESYNCF="/opt/var/run/qwdtt.timesync"
TIME_SYNC_INTERVAL=3600
LOG_MAX_KB=512
. "$CONF" 2>/dev/null
# ПРАВА КОНФИГА ЧИНИМ САМИ, при каждом запуске.
#
# 05.09.2026 у владельца конфиг лежал 0644, а в нём PASSWORD туннеля. Виновата
# была правка через `mv` в qwdtt-ctl (там уже исправлено), но починка ТАМ не
# лечит роутеры, где права уже сбиты: конфиг больше никто не перезапишет.
# Одна строка здесь чинит их все при ближайшей перезагрузке.
#
# chmod без проверки текущего режима: `stat` в BusyBox есть не всегда, а
# повторный chmod на уже правильных правах ничего не стоит.
[ -f "$CONF" ] && chmod 600 "$CONF" 2>/dev/null

# Постоянный уникальный ID устройства — генерируется один раз и сохраняется
# в конфиге. Нужен, чтобы сервер не путал разных клиентов друг с другом.
if [ -z "$DEVICE_ID" ]; then
	DEVICE_ID=$(cat /proc/sys/kernel/random/uuid 2>/dev/null | tr -d '\n')
	[ -z "$DEVICE_ID" ] && DEVICE_ID="dev$(date +%s)$$"
	echo "DEVICE_ID=\"$DEVICE_ID\"" >> "$CONF"
fi

# РЕЖИМ КЛИЕНТА — ВИДИМОЙ СТРОКОЙ В КОНФИГЕ, А НЕ ПОДРАЗУМЕВАЕМЫМ УМОЛЧАНИЕМ.
#
# 20.09.2026 это стоило дня и двенадцати абонентов. Строку MODE в конфиг не
# писал НИКОГДА ни один скрипт раздачи (проверено грепом по всей раздаче,
# включая откатные копии), а умолчание было ${MODE:-raw}. Роутер без строки
# уходил в режим WG: RAW-туннеля там нет ПО ЗАМЫСЛУ, интерфейса meridian нет,
# движок вечно ждёт его и держит tunnel_state=down, а watchdog в этом режиме
# проверяет только «слушает ли 127.0.0.1:9000» и молчит ЗАКОННО. Получался
# нерабочий роутер без единого наблюдателя и без единой строки об ошибке.
#
# Поэтому три вещи сразу, а не одно перевёрнутое умолчание:
#   1. умолчание перевёрнуто в raw;
#   2. строка ДОПИСЫВАЕТСЯ в конфиг — умолчание становится видимым фактом,
#      который человек читает глазами и может изменить;
#   3. в журнал громкая строка, один раз, в момент записи.
#
# Попасть в режим WG теперь можно ТОЛЬКО явным MODE="wg", поставленным рукой.
# Случайно — нельзя.
if [ -z "$MODE" ]; then
	MODE="raw"
	mkdir -p "$(dirname "$LOG")" 2>/dev/null
	if [ -f "$CONF" ] && echo 'MODE="raw"' >> "$CONF" 2>/dev/null && grep -q '^MODE="raw"' "$CONF" 2>/dev/null; then
		echo "$(date): [режим] MODE не был задан в $CONF — поставил raw и дописал строку" >> "$LOG"
	else
		# Записать не вышло (нет конфига, права, место). Работаем в raw всё
		# равно, но говорим КАЖДЫЙ раз: невидимое умолчание — ровно то, из-за
		# чего мы сюда попали.
		echo "$(date): [режим] MODE не задан, строку в $CONF записать НЕ УДАЛОСЬ — работаю в raw, почините конфиг" >> "$LOG"
	fi
fi

# NTP по чистым IP (без DNS) — на случай, если DoT/DoH не может пройти
# TLS-проверку из-за неверного времени после перезагрузки роутера.
NTP_IPS="132.163.97.1 132.163.97.2 132.163.97.3 162.159.200.1 85.21.78.8"
NTP_HOSTS="ru.pool.ntp.org pool.ntp.org time.google.com"

rotate_log() {
	[ -f "$LOG" ] || return 0
	SIZE_KB=$(( $(wc -c < "$LOG" 2>/dev/null || echo 0) / 1024 ))
	if [ "$SIZE_KB" -gt "$LOG_MAX_KB" ] 2>/dev/null; then
		# ВАЖНО: обрезаем файл НА МЕСТЕ, а не подменяем его через mv.
		# Клиент запущен как `"$BIN" ... >> "$LOG"` и держит открытый
		# дескриптор на конкретный inode. После mv его вывод продолжает
		# уходить в УДАЛЁННЫЙ файл: в логе тишина до самого перезапуска
		# клиента, а место на флеше занято невидимо (du не видит, df
		# видит). Ровно так получилась дыра 22:00-08:39 в ночь на
		# 14.08.2026 при полностью живом туннеле.
		tail -200 "$LOG" > "$LOG.tmp" 2>/dev/null && cat "$LOG.tmp" > "$LOG"
		rm -f "$LOG.tmp"
		echo "$(date): лог обрезан (был ${SIZE_KB}KB, лимит ${LOG_MAX_KB}KB)" >> "$LOG"
	fi
}

sync_time_if_needed() {
	YEAR=$(date +%Y 2>/dev/null)
	if [ -n "$YEAR" ] && [ "$YEAR" -ge 2024 ] 2>/dev/null; then
		return 0
	fi
	echo "$(date): системное время неверное (год=$YEAR), синхронизирую" >> "$LOG"
	command -v ntpd >/dev/null 2>&1 || { echo "$(date): ntpd не найден" >> "$LOG"; return 1; }
	for ip in $NTP_IPS; do
		ntpd -n -q -p "$ip" >/dev/null 2>&1
		Y2=$(date +%Y 2>/dev/null)
		if [ -n "$Y2" ] && [ "$Y2" -ge 2024 ] 2>/dev/null; then
			echo "$(date): время синхронизировано по IP $ip" >> "$LOG"; return 0
		fi
	done
	for srv in $NTP_HOSTS; do
		ntpd -n -q -p "$srv" >/dev/null 2>&1
		Y2=$(date +%Y 2>/dev/null)
		if [ -n "$Y2" ] && [ "$Y2" -ge 2024 ] 2>/dev/null; then
			echo "$(date): время синхронизировано по домену $srv" >> "$LOG"; return 0
		fi
	done
	echo "$(date): синхронизация не удалась" >> "$LOG"; return 1
}

# periodic_time_check: вызывается из watchdog (раз в 5 мин), но реально
# синхронизирует время не чаще TIME_SYNC_INTERVAL (по умолчанию раз в час) —
# и, в отличие от sync_time_if_needed, делает это БЕЗУСЛОВНО, не дожидаясь,
# пока "год выглядит неверным". Так ловится и постепенный дрейф часов
# (RTC без батарейки, заблокированный штатный NTP роутера и т.п.), который
# не пересекает границу года и потому не отловился бы старой проверкой,
# но всё равно может сломать TLS/DTLS-рукопожатие с сервером.
periodic_time_check() {
	NOW=$(date +%s 2>/dev/null || echo 0)
	LAST=0
	[ -f "$TIMESYNCF" ] && LAST=$(cat "$TIMESYNCF" 2>/dev/null || echo 0)
	DIFF=$((NOW - LAST))
	if [ "$DIFF" -lt "$TIME_SYNC_INTERVAL" ] 2>/dev/null && [ "$LAST" != "0" ]; then
		return 0
	fi
	command -v ntpd >/dev/null 2>&1 || return 1
	for ip in $NTP_IPS; do
		if ntpd -n -q -p "$ip" >/dev/null 2>&1; then
			echo "$(date): [время] периодическая синхронизация по IP $ip" >> "$LOG"
			date +%s > "$TIMESYNCF" 2>/dev/null
			return 0
		fi
	done
	for srv in $NTP_HOSTS; do
		if ntpd -n -q -p "$srv" >/dev/null 2>&1; then
			echo "$(date): [время] периодическая синхронизация по домену $srv" >> "$LOG"
			date +%s > "$TIMESYNCF" 2>/dev/null
			return 0
		fi
	done
	echo "$(date): [время] периодическая синхронизация не удалась (сеть недоступна?)" >> "$LOG"
	date +%s > "$TIMESYNCF" 2>/dev/null
	return 1
}

is_running() {
	[ -f "$PIDF" ] && kill -0 "$(cat "$PIDF")" 2>/dev/null
}

# Защита от гонки при старте: boot-time "start" и первый прогон watchdog по
# крону иногда пересекаются по времени — оба могут увидеть "процесса нет"
# (узкое окно между запуском процесса в фоне и записью его PID в $PIDF) и
# оба вызвать launch_now(), получаются два параллельных процесса qwdtt,
# конкурирующих за один TUN/один пароль (наблюдалось на практике). mkdir
# атомарен на POSIX ФС — простой лок без внешних зависимостей (flock может
# отсутствовать в этом BusyBox-окружении).
LOCKDIR="/opt/var/run/qwdtt.startlock"

launch_locked() {
	mkdir -p "$(dirname "$LOCKDIR")" 2>/dev/null
	tries=0
	while ! mkdir "$LOCKDIR" 2>/dev/null; do
		if [ -f "$LOCKDIR/ts" ]; then
			LOCKTS=$(cat "$LOCKDIR/ts" 2>/dev/null)
			if [ -n "$LOCKTS" ]; then
				LOCKAGE=$(( $(date +%s) - LOCKTS ))
				if [ "$LOCKAGE" -gt 30 ]; then
					# Зависший лок от упавшего процесса, который не убрал
					# за собой — считаем недействительным.
					rm -rf "$LOCKDIR" 2>/dev/null
					continue
				fi
			fi
		fi
		tries=$((tries+1))
		[ "$tries" -gt 15 ] && return 1
		sleep 1
	done
	date +%s > "$LOCKDIR/ts" 2>/dev/null
	# Повторная проверка УЖЕ ПОД локом — вдруг пока мы его ждали, другой
	# запуск (тот, что держал лок до нас) уже поднял процесс.
	if ! is_running; then
		launch_now
	fi
	rm -rf "$LOCKDIR" 2>/dev/null
}

# extract_wg_from_log: достаёт полный блок WG-конфига из лога, если он там
# ещё есть. Используется ТОЛЬКО сразу после старта, пока лог свежий —
# на активном туннеле лог многословный и ротируется (LOG_MAX_KB) за минуты,
# так что искать этот блок постфактум (например, по клику в панели спустя
# долгое время после старта) уже бессмысленно — его там давно не будет.
extract_wg_from_log() {
	[ -f "$LOG" ] || return 1
	PRIV=$(sed -n 's/.*[[:space:]]PrivateKey[[:space:]]*=[[:space:]]*\([^[:space:]]*\).*/\1/p' "$LOG" | tail -1)
	ADDR=$(sed -n 's/.*[[:space:]]Address[[:space:]]*=[[:space:]]*\([^[:space:]]*\).*/\1/p' "$LOG" | tail -1)
	PUB=$(sed -n 's/.*[[:space:]]PublicKey[[:space:]]*=[[:space:]]*\([^[:space:]]*\).*/\1/p' "$LOG" | tail -1)
	ALLOWED=$(sed -n 's/.*[[:space:]]AllowedIPs[[:space:]]*=[[:space:]]*\([^[:space:]]*\).*/\1/p' "$LOG" | tail -1)
	ENDPOINT=$(sed -n 's/.*[[:space:]]Endpoint[[:space:]]*=[[:space:]]*\([^[:space:]]*\).*/\1/p' "$LOG" | tail -1)
	if [ -z "$PRIV" ] || [ -z "$ADDR" ] || [ -z "$PUB" ] || [ -z "$ENDPOINT" ]; then
		return 1
	fi
	[ -z "$ALLOWED" ] && ALLOWED="0.0.0.0/0"
	printf '[Interface]\nPrivateKey = %s\nAddress = %s\nDNS = 1.1.1.1\nMTU = 1280\n\n[Peer]\nPublicKey = %s\nAllowedIPs = %s\nEndpoint = %s\nPersistentKeepalive = 25\n' \
		"$PRIV" "$ADDR" "$PUB" "$ALLOWED" "$ENDPOINT"
	return 0
}

# capture_wg_config: вызывается в фоне сразу после запуска процесса.
# До 60 секунд ждёт появления блока конфига в свежем логе и, как только
# найдёт, сохраняет его в $WG — это единственный надёжный момент поймать
# его, пока ротация лога не успела вытеснить эти строки.
capture_wg_config() {
	i=0
	while [ "$i" -lt 30 ]; do
		CFG=$(extract_wg_from_log)
		if [ -n "$CFG" ]; then
			echo "$CFG" > "$WG" 2>/dev/null
			echo "$(date): [конфиг] WG-конфиг пойман и сохранён в $WG" >> "$LOG"
			return 0
		fi
		sleep 2
		i=$((i+1))
	done
	echo "$(date): [конфиг] не удалось поймать WG-блок за 60 сек после старта" >> "$LOG"
}

# ---------- NAT из локалки в RAW-туннель ----------
# Без MASQUERADE на TUN клиент локальной сети уходит в туннель со СВОИМ
# адресом 192.168.x.x, а NAT на шлюзе покрывает только 10.77.77.0/24 — такие
# пакеты уходят наружу, но ответы не возвращаются. Пинг с самого роутера при
# этом проходит (у него источник 10.77.77.x), поэтому дефект выглядит как
# «туннель живой, а обход не работает», и ищется он не там. Проверено на
# практике: правило добавили руками — обход заработал немедленно, вторым
# хопом в трассировке из локалки стал 10.77.77.1.
#
# Правило волатильное: не переживает перезагрузку и исчезает вместе с
# пересозданным интерфейсом. Поэтому ставим при каждом старте и подтверждаем
# из watchdog, а при остановке снимаем, чтобы дубликаты не копились.
raw_tun_name() { echo "${RAW_TUN:-meridian}"; }

ensure_masq() {
	[ "${MODE:-raw}" = "raw" ] || return 0
	IFACE=$(raw_tun_name)
	ip link show "$IFACE" >/dev/null 2>&1 || return 1
	iptables -t nat -C POSTROUTING -o "$IFACE" -j MASQUERADE 2>/dev/null && return 0
	if iptables -t nat -A POSTROUTING -o "$IFACE" -j MASQUERADE 2>/dev/null; then
		echo "$(date): [NAT] MASQUERADE на $IFACE добавлен" >> "$LOG"
		return 0
	fi
	echo "$(date): [NAT] не удалось добавить MASQUERADE на $IFACE" >> "$LOG"
	return 1
}

# ensure_masq_when_up — интерфейс создаёт сам клиент, уже ПОСЛЕ запуска
# процесса, поэтому поставить правило сразу нельзя: интерфейса ещё нет.
# Ждём его появления ограниченное время и выходим в любом случае — у роутера
# 248 МБ и активный OOM-киллер, вечных фоновых ожиданий здесь быть не должно.
ensure_masq_when_up() {
	i=0
	while [ "$i" -lt 60 ]; do
		if ensure_masq; then return 0; fi
		sleep 2
		i=$((i+1))
	done
	echo "$(date): [NAT] интерфейс $(raw_tun_name) не появился за 120 с, MASQUERADE не поставлен" >> "$LOG"
	return 1
}

# remove_masq — снимает ВСЕ свои правила, а не одно: за долгую жизнь роутера
# их могло накопиться несколько.
remove_masq() {
	IFACE=$(raw_tun_name)
	tries=0
	while iptables -t nat -C POSTROUTING -o "$IFACE" -j MASQUERADE 2>/dev/null; do
		iptables -t nat -D POSTROUTING -o "$IFACE" -j MASQUERADE 2>/dev/null || break
		echo "$(date): [NAT] MASQUERADE на $IFACE снят" >> "$LOG"
		tries=$((tries+1))
		[ "$tries" -gt 10 ] && break
	done
}

# ---------------------------------------------------------------------------
# Вызов движка маршрутизации. Раньше здесь стояли три строки вида
# `[ -x путь ] && путь команда || true`, и такая охрана ПРЯЧЕТ отсутствие
# зависимости: «движка нет» и «движок отработал» выглядят одинаково — тишиной.
# Именно поэтому промах после переименования (скрипты звали qwdtt-route, движок
# стоял как meridian-route) прожил три дня и стоил клиентам молчаливых обрывов.
#
# Три состояния вместо двух:
#   есть                     — зовём, запоминаем, что он тут был;
#   нет и никогда не было    — ШТАТНО (движок доставляется не на все роутеры),
#                              молчим: иначе зальём логи парка не-проблемой;
#   нет, но ОЖИДАЕТСЯ        — одна строка в лог, с причиной.
#
# Ожидание определяется двумя независимыми признаками:
#   1) крючок движка на месте, а бинаря по НАШЕМУ пути нет — значит пути
#      разошлись. Настоящий путь берём из тела крючка (строка `exec <путь> …`)
#      и называем в сообщении ОБА. Это и есть тот случай, который был;
#   2) движок здесь БЫЛ раньше (метка на флеше), а теперь его нет — пропал.
# ---------------------------------------------------------------------------
ROUTE_BIN="${ROUTE_BIN:-/opt/bin/meridian-route}"
ROUTE_HOOK="${ROUTE_HOOK:-/opt/etc/ndm/netfilter.d/50-meridian-route.sh}"
ROUTE_SEEN="${ROUTE_SEEN:-/opt/etc/qwdtt/.route_seen}"      # флеш: пережить перезагрузку
ROUTE_SAID="${ROUTE_SAID:-/opt/var/run/qwdtt.route_said}"   # tmpfs: одна строка на загрузку

# route_say_missing_once — сказать ОДИН раз и только если движок ожидается.
# Подавление по метке-ФАЙЛУ, а не по тексту: тексты различаются подставленным
# путём, подавление по тексту не сработало бы ни разу (правило 21).
route_say_missing_once() {
	[ -f "$ROUTE_SAID" ] && return 0
	REAL=""
	[ -f "$ROUTE_HOOK" ] && REAL=$(sed -n 's/^exec \([^ ][^ ]*\) .*/\1/p' "$ROUTE_HOOK" | head -1)
	if [ -n "$REAL" ] && [ "$REAL" != "$ROUTE_BIN" ]; then
		: > "$ROUTE_SAID"
		# Совет безопасный, как и в route_check_sum: `repair` без --list
		# переустанавливает ВСЁ, что разошлось с раздачей, и на роутере с
		# кандидатом откатил бы его до опубликованного.
		rlog "зову $ROUTE_BIN, а движок установлен по $REAL — вызовы уходят в никуда. Пути разошлись; посмотреть, что именно: qwdtt-ctl repair --list"
		return 0
	fi
	# Жаловаться на пропажу можно только ПОСЛЕ того, как доставка попробовала и не
	# смогла. Иначе на чистом роутере паника печатается за секунды до того, как файл
	# появится сам (найдено владельцем на входе 1, 22.08.2026).
	if [ -f "$ROUTE_SEEN" ] && [ -f "$ROUTE_TRIED" ]; then
		: > "$ROUTE_SAID"
		rlog "движка $ROUTE_BIN нет, и доставка его не принесла — свои маршруты не восстанавливаются. Запусти qwdtt-ctl repair."
		return 0
	fi
	if [ -f "$ROUTE_SEEN" ]; then
		: > "$ROUTE_SAID"
		rlog "движка $ROUTE_BIN сейчас нет — он будет доставлен автоматически при подъёме туннеля. Если не появится, запусти qwdtt-ctl repair."
		return 0
	fi
	return 0
}

# ---------------------------------------------------------------------------
# ДОСТАВКА ДВИЖКА. Правила, из которых написан этот кусок (приёмка 22.08.2026):
#   * качаем ТОЛЬКО когда файла нет. Обновление версии — явным действием
#     (кнопка панели или `qwdtt-ctl repair`), иначе одна плохая версия молча
#     разъедется по всему парку при следующем старте;
#   * доставка НЕ на критическом пути: отдельный процесс ждёт подъёма туннеля и
#     только потом идёт в сеть. Порядок строк в логе это доказывает;
#   * одна попытка за старт = ОДИН обход всего списка адресов, не один запрос;
#   * сумма — условие ПОДМЕНЫ, а не повод лезть в сеть;
#   * у ожидателя есть ПРЕДЕЛ, имя (по глаголу) и строка при выходе по пределу.
# ---------------------------------------------------------------------------
ROUTE_WAIT_MAX="${ROUTE_WAIT_MAX:-180}"   # ЕДИНСТВЕННОЕ место, где задан предел ожидания, с
ROUTE_SHA="${ROUTE_SHA:-${QWDTT_CONF_DIR:-/opt/etc/qwdtt}/.meridian-route.sha}"
# ROUTE_TRIED — доставка В ЭТОМ СТАРТЕ уже отработала и не принесла файл. Нужна для
# ПОРЯДКА: жаловаться на отсутствие движка можно только ПОСЛЕ того, как доставка
# попробовала, иначе на чистом роутере паника печатается за секунды до того, как файл
# появится сам. СБРАСЫВАЕТСЯ В НАЧАЛЕ КАЖДОГО start (:ниже): tmpfs переживает
# перезапуск клиента, и без сброса сообщение говорило бы о ПРОШЛОМ старте как о
# текущем (найдено владельцем 22.08.2026).
ROUTE_TRIED="${ROUTE_TRIED:-/opt/var/run/qwdtt.route_tried}"
# ROUTE_WAIT_PID — PID живого ожидателя. Нужен по двум причинам:
#   1) второго ожидателя не заводим, пока жив первый. Сторож перезапускает клиента
#      каждые 300 с, предел ожидателя 180 с — в норме не перекрываются, но ручной
#      перезапуск поверх сторожевого давал двух (найдено на входе 2в 22.08.2026);
#   2) проверка может следить за СУДЬБОЙ КОНКРЕТНОГО процесса, а не считать штуки:
#      «тот же не ушёл» и «появился новый» иначе выглядят одинаково.
ROUTE_WAIT_PID="${ROUTE_WAIT_PID:-/opt/var/run/qwdtt.route_wait.pid}"
# Список источников. QWDTT_DIST_BASE ЗАМЕНЯЕТ его целиком (только для прогонов):
# добавление вторым адресом означало бы, что проверка «раздача недоступна» тайком
# сходила в живую раздачу и оказалась зелёной и пустой одновременно (правило 20).
ROUTE_BASES="${QWDTT_DIST_BASE:-http://10.77.77.1:8080/bin http://10.66.66.1:8080/bin http://138.124.78.252:8080/bin}"

# ---------------------------------------------------------------------------
# Пределы доставки (пункт 7, решения владельца 24.08.2026).
#
# Почему у внутренних адресов СВОЙ, короткий предел подключения. Внутренние живут
# внутри туннеля: если туннель мёртв, они не ответят никогда, и ждать их полным
# пределом — терять минуты на заведомо мёртвом. Но и ПРОПУСКАТЬ их нельзя: пропуск
# был бы догадкой «туннеля нет», а 4 секунды на отказ — измерением. Публичному
# адресу предел подключения обычный: он отвечает и без туннеля, ради него всё.
ROUTE_CONNECT_INNER="${ROUTE_CONNECT_INNER:-4}"    # с, подключение к адресу внутри туннеля
ROUTE_CONNECT_PUBLIC="${ROUTE_CONNECT_PUBLIC:-5}"  # с, подключение к публичному
ROUTE_XFER_MAX="${ROUTE_XFER_MAX:-60}"             # с, передача файла с любого источника
# Предел на ВСЮ попытку. Считается по НАЧАЛУ обращения к очередному источнику:
# уже начавшаяся передача не обрывается — иначе мы резали бы файл на середине у
# медленного клиента, а это ровно тот «огрызок», от которого защищаемся.
ROUTE_TOTAL_MAX="${ROUTE_TOTAL_MAX:-300}"          # с, на весь обход списка

# route_is_inner — адрес ведёт внутрь туннеля? Решается по подсети, а не по номеру
# в списке: список переопределяется прогоном целиком, и «первые два — внутренние»
# перестало бы быть правдой молча.
route_is_inner() {
	case "$1" in
		*10.77.77.*|*10.66.66.*) return 0 ;;
		*) return 1 ;;
	esac
}

# ROUTE_RETRY — состояние повторных попыток: когда пробовали в последний раз,
# сколько попыток было, когда последний раз печатали суточный маячок.
# В tmpfs НАМЕРЕННО (решение владельца): ежечасная запись на флеш годами — износ,
# а сброс при перезагрузке здесь правильное поведение — свежая загрузка заслуживает
# свежей попытки. Формат: три числа через пробел «время_попытки число_попыток время_маячка».
ROUTE_RETRY="${ROUTE_RETRY:-/opt/var/run/qwdtt.route_retry}"
# ROUTE_SELF — путь к этому скрипту. По нему замок узнаёт СВОЙ процесс: номера PID
# ядро выдаёт по кругу, и «kill -0 прошёл» отвечает на вопрос «номер занят», а не
# «занят нами». Через сутки под тем же номером живёт что угодно.
ROUTE_SELF="${ROUTE_SELF:-$0}"
# Расписание повторов от загрузки клиента: 5-я минута, 15-я, дальше каждый час.
# Не плоский час: типичный случай — роутер включили вместе с модемом провайдера, и
# интернет появился через три-пять минут; при плоском часе клиент ждёт час впустую.
ROUTE_RETRY_EARLY1="${ROUTE_RETRY_EARLY1:-300}"    # с от загрузки: первая попытка
ROUTE_RETRY_EARLY2="${ROUTE_RETRY_EARLY2:-900}"    # с: вторая
ROUTE_RETRY_EVERY="${ROUTE_RETRY_EVERY:-3600}"     # с: дальше раз в час
ROUTE_RETRY_BEACON="${ROUTE_RETRY_BEACON:-86400}"  # с: суточный маячок в лог

rlog() { echo "$(date '+%Y-%m-%d %H:%M:%S') [МАРШРУТ] $*" >> "$LOG"; }

# route_fetch <база> <куда> — принести файл одним загрузчиком, без своих таймаутов
# сверх заданных: `wget -T` на части прошивок падает по сигналу (правило 33).
# route_fetch <база> <куда> [файл] — принести файл с ОДНОГО источника, с пределом.
#
# Предел на источник ПРОВЕРЯЕТСЯ, а не предполагается. У curl он есть ключами. У
# wget ключ -T ставить нельзя: на части сборок BusyBox его нет, и wget не ругается,
# а ПАДАЕТ ПО СИГНАЛУ (правило 33, стоило двух срывов установки 18.08). Поэтому
# порядок форм такой же, как в install.sh: сначала curl, потом wget под внешним
# `timeout`, и только если и его нет — голый wget, о чём говорится вслух.
# Без этого «предел на источник» был бы словами: на прошивке без curl мёртвый
# адрес держал бы доставку до умолчания BusyBox (в части сборок 900 с).
route_fetch() {
	_base="$1"; _dst="$2"; _name="${3:-meridian-route}"
	if route_is_inner "$_base"; then _conn="$ROUTE_CONNECT_INNER"; else _conn="$ROUTE_CONNECT_PUBLIC"; fi
	if command -v curl >/dev/null 2>&1; then
		curl -fsSL --connect-timeout "$_conn" --max-time "$ROUTE_XFER_MAX" \
			-o "$_dst" "$_base/$_name" 2>/dev/null && [ -s "$_dst" ] && return 0
		return 1
	fi
	if command -v timeout >/dev/null 2>&1 && command -v wget >/dev/null 2>&1; then
		timeout "$ROUTE_XFER_MAX" wget -q -O "$_dst" "$_base/$_name" 2>/dev/null && [ -s "$_dst" ] && return 0
		return 1
	fi
	if command -v wget >/dev/null 2>&1; then
		# Предела нет и взять его негде. Говорим об этом, а не делаем вид.
		rlog "предупреждение: нет ни curl, ни timeout — скачивание с $_base идёт БЕЗ предела"
		wget -q -O "$_dst" "$_base/$_name" 2>/dev/null && [ -s "$_dst" ] && return 0
		return 1
	fi
	return 1
}

# route_deliver — ОДИН обход списка. Пишет ровно одну строку «пробую принести» и
# ровно одну об исходе; отдельных строк на адрес нет (правило 21).
route_deliver() {
	# ДОСТАВКА ИДЁТ ТОЛЬКО ПРИ ОТСУТСТВИИ ФАЙЛА — и это условие, а не оптимизация.
	# Убрать эту строку значит завести обновление ПОВЕРХ работающего движка, а для
	# него нужен откат (бэкап прежнего и возврат по неудачному запуску), которого у
	# нас нет. Тогда привезённый плохой файл заменит рабочий безвозвратно.
	# Проверяется тестом «рабочий движок остался побайтно тем же» (см. стенд).
	[ -x "$ROUTE_BIN" ] && return 0
	# ГРОМКОСТЬ. Строка о неудаче печатается ОДИН раз за загрузку: ROUTE_TRIED уже
	# существует — значит в этом старте мы уже жаловались, и повтор ничего не
	# добавит, кроме роста лога (правило 21: повторы в цикле подавляются по
	# ФИКСИРОВАННОЙ метке, а не по тексту — тексты различаются причинами).
	# Дальше о неудачах говорит суточный маячок из route_retry.
	if [ -f "$ROUTE_TRIED" ]; then _loud=0; else _loud=1; fi
	TMP="$ROUTE_BIN.incoming"; FAILED=""; _srcn=$(echo $ROUTE_BASES | wc -w)
	_started=$(date +%s 2>/dev/null || echo 0)
	for B in $ROUTE_BASES; do
		# Общий предел проверяется ПЕРЕД обращением к очередному источнику: уже
		# начавшаяся передача не обрывается (решение владельца 24.08).
		_now=$(date +%s 2>/dev/null || echo 0)
		if [ "$_started" -gt 0 ] && [ $(( _now - _started )) -ge "$ROUTE_TOTAL_MAX" ]; then
			FAILED="$FAILED $B (не пробовал: вышел общий предел ${ROUTE_TOTAL_MAX} с)"
			continue
		fi
		rm -f "$TMP"
		route_fetch "$B" "$TMP" || { FAILED="$FAILED $B (не скачалось)"; continue; }
		head -c 4 "$TMP" 2>/dev/null | grep -q '#!' || { FAILED="$FAILED $B (не скрипт)"; rm -f "$TMP"; continue; }
		SUMS="$TMP.sums"; rm -f "$SUMS"
		route_fetch "$B" "$SUMS" "SHA256SUMS" || true
		WANT=$(awk '$2 == "meridian-route" {print $1}' "$SUMS" 2>/dev/null | head -1)
		rm -f "$SUMS"
		# Дальше — ДВА исхода, на которых прежняя редакция СДАВАЛАСЬ (`return 1`),
		# не пробуя остальные источники. Один протухший или битый источник не должен
		# класть доставку целиком, когда рядом есть исправный (решение владельца
		# 24.08). Поэтому `continue`, а причина называется поимённо.
		if [ -z "$WANT" ]; then
			rm -f "$TMP"; FAILED="$FAILED $B (суммы для meridian-route в манифесте нет)"; continue
		fi
		GOT=$(sha256sum "$TMP" 2>/dev/null | awk '{print $1}')
		if [ "$GOT" != "$WANT" ]; then
			rm -f "$TMP"
			FAILED="$FAILED $B (сумма не совпала: пришло $(echo "$GOT" | cut -c1-16), ждали $(echo "$WANT" | cut -c1-16))"
			continue
		fi
		chmod +x "$TMP" 2>/dev/null
		mv -f "$TMP" "$ROUTE_BIN" || { rm -f "$TMP"; FAILED="$FAILED $B (подмена не прошла)"; continue; }
		# Эталон пишем ТОЛЬКО после подтверждения суммы манифестом: эталон, снятый с
		# лежащего файла, — отпечаток, и сверка с ним не может покраснеть.
		echo "$WANT" > "$ROUTE_SHA" 2>/dev/null
		rm -f "$ROUTE_TRIED" 2>/dev/null
		# Отвергнутые источники называем ЗДЕСЬ, а не отдельной строкой: источник,
	# отдающий файл с чужой суммой, — это находка, и молчать о ней нельзя, но и
	# строки на каждый адрес заводить нельзя (правило 21).
	# Номер попытки в строке успеха: «принесли с седьмого раза за шесть часов» и
	# «принесли сразу» — разные новости, а строка без номера делает их одной.
	rlog "принёс движок с $B (сумма $(echo "$WANT" | cut -c1-16); источников было $_srcn${ROUTE_ATTEMPT:+; попытка $ROUTE_ATTEMPT-я})${FAILED:+; пропущены:$FAILED}"
		return 0
	done
	ROUTE_WHY="ни один из $_srcn источников не отдал годный файл —$FAILED"
	: > "$ROUTE_TRIED" 2>/dev/null
	# ОТДЕЛЬНОЕ СОСТОЯНИЕ, а не тишина: «доставлять было нечего» и «пробовали, никто
	# не ответил» обязаны различаться, иначе половина дефекта остаётся на месте.
	# Одной строкой: причина, что будет дальше и что сделать руками.
	[ "$_loud" = 1 ] && rlog "НЕ ДОСТАВЛЕН: $ROUTE_WHY. Буду пробовать снова сам; починить сейчас — qwdtt-ctl repair"
	return 1
}

# route_wait — ОТДЕЛЬНЫЙ процесс (запускается глаголом, поэтому виден в ps как
# «S99qwdtt route-wait»): ждёт подъёма туннеля с ПРЕДЕЛОМ и только потом доставляет.
route_wait() {
	[ "${MODE:-raw}" = "raw" ] || exit 0
	[ -x "$ROUTE_BIN" ] && exit 0
	route_busy && { rlog "доставка уже идёт — второго ожидателя не завожу"; exit 0; }
	# ДВА обработчика, а не один. Пойманный сигнал в ash выполняет обработчик и
	# ВОЗВРАЩАЕТСЯ туда, где прервался: с общим обработчиком на EXIT INT TERM
	# ожидатель по `kill` снимал свой замок и продолжал ждать и доставлять — то
	# есть остановка не останавливала, а только развязывала руки второму
	# ожидателю. Найдено 25.08.2026 на собственном прогоне: убитый в случае 7
	# ожидатель дожил до случая 9 и доставил движок там, где его быть не должно.
	trap 'rm -f "$ROUTE_WAIT_PID" 2>/dev/null' EXIT
	trap 'rm -f "$ROUTE_WAIT_PID" 2>/dev/null; exit 0' INT TERM
	echo "$$" > "$ROUTE_WAIT_PID" 2>/dev/null
	route_retry_init
	IFACE=$(raw_tun_name); i=0
	while [ "$i" -lt "$ROUTE_WAIT_MAX" ]; do
		if ping -c 1 -W 2 -I "$IFACE" 8.8.8.8 >/dev/null 2>&1; then
			rlog "туннель поднялся за ${i} с — начинаю доставку движка"
			route_deliver
			route_retry_note "$?"
			exit 0
		fi
		i=$((i + 1)); sleep 1
	done
	# ПУНКТ 7. Раньше здесь стояло «доставку движка отменяю» — и это связывало
	# доставку с туннелем, которого без движка может не быть вовсе. Публичный
	# источник отвечает и БЕЗ туннеля; внутренние в этом случае просто откажут за
	# свои 4 секунды, и это измерение, а не догадка. Ждём мы ради внутренних —
	# они ближе и не идут наружу, — но отказ ожидания не отменяет попытку.
	rlog "туннель не поднялся за ${ROUTE_WAIT_MAX} с — доставку всё равно пробую: публичный источник отвечает и без туннеля"
	route_deliver
	route_retry_note "$?"
	exit 0
}

# ---------------------------------------------------------------------------
# ЗАМОК ДОСТАВКИ. Один держатель на роутер: ожидатель при старте и повтор из
# сторожа ходят в сеть одним и тем же путём и одним и тем же временным именем.
# ---------------------------------------------------------------------------
# route_busy — доставка уже идёт? Отвечает не «занят ли номер PID», а «занят ли он
# НАМИ»: номера переиспользуются, и через сутки под тем же числом живёт чужой
# процесс. Чужой номер = замок брошен: снимаем файл и работаем дальше, а не ждём
# вечно того, кого нет.
route_busy() {
	_wp=$(cat "$ROUTE_WAIT_PID" 2>/dev/null)
	[ -n "$_wp" ] || return 1
	kill -0 "$_wp" 2>/dev/null || { rm -f "$ROUTE_WAIT_PID" 2>/dev/null; return 1; }
	_cl=$(tr '\0' ' ' < "/proc/$_wp/cmdline" 2>/dev/null)
	case "$_cl" in
		*"$ROUTE_SELF"*)
			case "$_cl" in
				*route-wait*|*watchdog*) return 0 ;;
			esac
			;;
	esac
	rlog "замок доставки держал чужой процесс (pid $_wp) — снимаю и продолжаю"
	rm -f "$ROUTE_WAIT_PID" 2>/dev/null
	return 1
}

# ---------------------------------------------------------------------------
# ПОВТОРНЫЕ ПОПЫТКИ (пункт 7). Состояние — одна строка из четырёх чисел:
#   <когда начали> <когда пробовали в последний раз> <сколько попыток> <когда маячили>
# вторая строка — причина последней неудачи, для суточного маячка.
# ---------------------------------------------------------------------------
route_retry_init() {
	[ -s "$ROUTE_RETRY" ] && return 0
	_t=$(date +%s 2>/dev/null || echo 0)
	printf '%s 0 0 %s\n' "$_t" "$_t" > "$ROUTE_RETRY" 2>/dev/null
}

# route_retry_note <код возврата route_deliver> — записать исход попытки.
route_retry_note() {
	if [ "$1" = 0 ]; then rm -f "$ROUTE_RETRY" 2>/dev/null; return 0; fi
	route_retry_init
	_t=$(date +%s 2>/dev/null || echo 0)
	set -- $(sed -n 1p "$ROUTE_RETRY" 2>/dev/null)
	_s="${1:-$_t}"; _n="${3:-0}"; _b="${4:-$_t}"
	{ printf '%s %s %s %s\n' "$_s" "$_t" "$(( _n + 1 ))" "$_b"
	  printf '%s\n' "${ROUTE_WHY:-причина не названа}"; } > "$ROUTE_RETRY" 2>/dev/null
}

# route_retry — зовётся сторожем (раз в 5 мин). Сам решает, пора ли, и говорит в
# лог только раз в сутки: без этого 24 попытки дали бы 24 строки в день на роутере,
# где лог живёт в 512 КБ (правило 21).
route_retry() {
	[ "${MODE:-raw}" = "raw" ] || return 0
	[ -x "$ROUTE_BIN" ] && { rm -f "$ROUTE_RETRY" 2>/dev/null; return 0; }
	route_busy && return 0
	_t=$(date +%s 2>/dev/null || echo 0); [ "$_t" -gt 0 ] || return 0
	route_retry_init
	set -- $(sed -n 1p "$ROUTE_RETRY" 2>/dev/null)
	_s="${1:-$_t}"; _last="${2:-0}"; _n="${3:-0}"; _b="${4:-$_t}"
	# Расписание: 5-я минута от старта, 15-я, дальше каждый час от последней
	# попытки. Отсчёт от СТАРТА, а не от последней попытки, ровно на первых двух:
	# иначе «через 5 минут» превращалось бы в «через 5 минут после того, как
	# сторож впервые дошёл сюда», то есть в неизвестно когда.
	# СУТОЧНЫЙ МАЯЧОК — до проверки «пора ли пробовать» и независимо от неё.
	# Если привязать его к попытке, срок маячка сдвигается на ближайшую попытку
	# после суток, и «раз в сутки» превращается в «когда получится». Проверено
	# красным входом: при привязке к попытке строка выходит на 87300-й секунде.
	route_beacon "$_t" "$_s" "$_n" "$_b"
	case "$_n" in
		0) _due=$(( _s + ROUTE_RETRY_EARLY1 )) ;;
		1) _due=$(( _s + ROUTE_RETRY_EARLY2 )) ;;
		*) _due=$(( _last + ROUTE_RETRY_EVERY )) ;;
	esac
	[ "$_t" -ge "$_due" ] || return 0
	trap 'rm -f "$ROUTE_WAIT_PID" 2>/dev/null' EXIT
	trap 'rm -f "$ROUTE_WAIT_PID" 2>/dev/null; exit 0' INT TERM
	echo "$$" > "$ROUTE_WAIT_PID" 2>/dev/null
	ROUTE_ATTEMPT=$(( _n + 1 ))
	route_deliver; _rc=$?
	ROUTE_ATTEMPT=""
	route_retry_note "$_rc"
	rm -f "$ROUTE_WAIT_PID" 2>/dev/null
	return "$_rc"
}

# route_beacon <сейчас> <начало> <попыток> <когда маячили> — сказать вслух раз в
# сутки. Молчание длиной в сутки не должно быть неотличимо от «всё хорошо».
route_beacon() {
	_bt="$1"; _bs="$2"; _bn="$3"; _bb="$4"
	[ $(( _bt - _bb )) -ge "$ROUTE_RETRY_BEACON" ] || return 0
	# Читаем состояние ЦЕЛИКОМ до записи: строка причины лежит в том же файле,
	# который мы сейчас перепишем, и вычитывать её из-под собственной записи —
	# способ однажды напечатать пустоту.
	set -- $(sed -n 1p "$ROUTE_RETRY" 2>/dev/null)
	_s2="${1:-$_bs}"; _last2="${2:-$_bt}"; _n2="${3:-$_bn}"
	_why=$(sed -n 2p "$ROUTE_RETRY" 2>/dev/null)
	{ printf '%s %s %s %s\n' "$_s2" "$_last2" "$_n2" "$_bt"
	  printf '%s\n' "$_why"; } > "$ROUTE_RETRY" 2>/dev/null
	rlog "движок так и не доставлен: попыток $_n2 за $(( ( _bt - _s2 ) / 3600 )) ч, последняя причина — ${_why:-причина не названа}. Роутер работает, свои маршруты не восстанавливаются; починить — qwdtt-ctl repair"
}

# route_check_sum — движок есть: сверяем с локальным эталоном и, если не сходится,
# говорим ОДИН раз за загрузку. Не качаем: обнаружение автоматическое, исправление
# осознанное (`qwdtt-ctl repair` или кнопка панели).
route_check_sum() {
	[ -x "$ROUTE_BIN" ] || return 0
	[ -f "$ROUTE_SHA" ] || return 0
	[ -f "$ROUTE_SAID" ] && return 0
	HAVE=$(sha256sum "$ROUTE_BIN" 2>/dev/null | awk '{print $1}')
	WANT=$(cat "$ROUTE_SHA" 2>/dev/null)
	[ -n "$HAVE" ] && [ -n "$WANT" ] && [ "$HAVE" != "$WANT" ] || return 0
	: > "$ROUTE_SAID"
	# ВЕРСИЯ ИЗ САМОГО ФАЙЛА, без запуска: движок — сценарий, и строка VERSION=
	# в нём есть. Человеку «стоит 1.19» говорит больше, чем шестнадцать знаков суммы.
	_v=$(grep -m1 '^VERSION=' "$ROUTE_BIN" 2>/dev/null | cut -d'"' -f2)
	# ДВА РАЗНЫХ СЛУЧАЯ, и путать их нельзя (05.09.2026).
	#
	# Эталон пишет ТОЛЬКО штатная доставка (route_fetch). Поставили кандидата
	# руками — сверка обязана разойтись, и это НЕ поломка. Прежний текст говорил
	# «движок не тот» и советовал `qwdtt-ctl repair`, а repair переустанавливает
	# всё, что разошлось с раздачей: на роутере с кандидатом 1.19 он откатил бы
	# движок до опубликованного и заодно переустановил клиент, панель, ctl и
	# init-скрипты. Совет, исполнение которого хуже болезни, — не совет.
	#
	# Отличаем по времени: бинарь НОВЕЕ эталона означает, что файл сменили после
	# последней штатной доставки. Это ровно признак ручной установки.
	if [ "$ROUTE_BIN" -nt "$ROUTE_SHA" ]; then
		rlog "движок${_v:+ $_v} поставлен не штатной доставкой: сумма $(echo "$HAVE" | cut -c1-16) не совпадает с эталоном $(echo "$WANT" | cut -c1-16), и это ожидаемо при ручной установке кандидата. Ничего делать не нужно; эталон обновится сам при следующей штатной доставке"
		return 0
	fi
	rlog "движок${_v:+ $_v} отличается от эталона: сумма $(echo "$HAVE" | cut -c1-16) вместо $(echo "$WANT" | cut -c1-16) — посмотреть, что разошлось: qwdtt-ctl repair --list"
}

# route_call <команда> — единственная точка вызова движка. Возвращает 0 всегда:
# отсутствие или отказ движка не должны ронять запуск и сторож.
route_call() {
	if [ -x "$ROUTE_BIN" ]; then
		[ -f "$ROUTE_SEEN" ] || : > "$ROUTE_SEEN" 2>/dev/null
		rm -f "$ROUTE_SAID" 2>/dev/null      # вернулся — сможем сказать снова
		"$ROUTE_BIN" "$@" || true
		return 0
	fi
	route_say_missing_once
	return 0
}

launch_now() {
	is_running && return 0
	rotate_log
	if [ "${MODE:-raw}" = "raw" ]; then
		RAW_PEER_ACTUAL="${RAW_PEER:-}"
		if [ -z "$RAW_PEER_ACTUAL" ]; then
			RAW_HOST=$(echo "$PEER" | cut -d: -f1)
			RAW_PEER_ACTUAL="${RAW_HOST}:56004"
		fi
		"$BIN" -mode raw -tun "${RAW_TUN:-meridian}" -peer "$RAW_PEER_ACTUAL" -password "$PASSWORD" -vk "$VK_HASHES" -vk-anon-path "${ANON_PATH:-vkcalls}" -n "${N:-24}" -device-id "$DEVICE_ID" < /dev/null >> "$LOG" 2>&1 &
		echo $! > "$PIDF"
		echo "$(date): запущен в режиме RAW, peer=$RAW_PEER_ACTUAL tun=${RAW_TUN:-meridian}" >> "$LOG"
		# Группы MagiTrickle переводим на наш tun не здесь, а в фоне — только
		# после того, как туннель действительно начнёт пропускать трафик.
		# Покрывает все пути запуска сразу: start, отложенный старт после
		# перезагрузки и подъём из watchdog (в том числе возврат групп после
		# аварийного отката на прежний интерфейс).
		( mt_raw_switch_when_up ) &
		# Интерфейс поднимет сам клиент через пару секунд — ждём его в фоне
		# и вешаем NAT, иначе локалка уйдёт в туннель без подмены адреса.
		( ensure_masq_when_up ) &
		# Доставка движка: ОТДЕЛЬНЫМ процессом с глаголом, а не подшеллом — только так
		# у него есть имя в ps (подшелл виден как «sleep», exec -a в ash нет).
		# Второго ожидателя не заводим, пока жив первый (см. ROUTE_WAIT_PID).
		if route_busy; then :; else sh "$0" route-wait >/dev/null 2>&1 & fi
	else
		"$BIN" -peer "$PEER" -password "$PASSWORD" -vk "$VK_HASHES" -vk-anon-path "${ANON_PATH:-vkcalls}" -n "${N:-24}" -device-id "$DEVICE_ID" -listen 127.0.0.1:9000 < /dev/null >> "$LOG" 2>&1 &
		echo $! > "$PIDF"
		( capture_wg_config ) &
	fi
	# ПОДЪЁМ СООБЩАЕТСЯ НА ОБЩЕМ ПУТИ — как и спуск.
	#
	# 05.09.2026, нашёл КОТ 1: этот вызов стоял ВНУТРИ ветки RAW, а парный
	# `on-tunnel-down` — на общем пути остановки. В режиме WG подъём не приходил
	# НИКОГДА. В логе движка за 22.08 из-за этого шесть «туннель упал» без
	# единого «поднят»: движок видел только половину событий и делал выводы по ней.
	#
	# Асимметрия вызовов опаснее их отсутствия. Отсутствие видно сразу — ничего
	# не работает; асимметрия работает наполовину и выглядит исправной. Движок
	# КОТ 1 уже научил определять состояние самому, но эта пара остаётся точкой,
	# на которую подпишется следующий, и он получит ту же мину.
	( route_call on-tunnel-up ) &
}

# --- MagiTrickle: переключение интерфейса групп вместе с режимом qwdtt ------
# У клиентов уже стоит MagiTrickle, и в его группах прописан WG-интерфейс
# (обычно nwg1). В RAW-режиме WG-интерфейса нет вообще — трафик идёт через
# наш tun. Если группы оставить на старом интерфейсе, у клиента не «медленно»,
# а просто отваливается интернет по всем «обходным» доменам.
# Всё ниже — no-op, если MagiTrickle не установлен: молча выходим.
#
# ЧТО ЗДЕСЬ ВАЖНО ЗНАТЬ (переработано 15.08.2026):
#
#  1. Разбор конфига идёт ПО ГРУППАМ, а не «первое попавшееся interface:».
#     Прежняя версия считала концом секции groups: любую строку, начинающуюся
#     не с пробела — а MagiTrickle пишет список с дефисом на нулевом отступе,
#     и разбор слеп на первой же группе. Симптом: «возвращать нечего (…: ?)»,
#     prev-файл не создавался, при падении туннеля группы оставались на
#     мёртвом интерфейсе.
#
#  2. Мы трогаем ТОЛЬКО «свои» группы. Своей считается группа, чей интерфейс
#     туннельный: наш RAW_TUN, либо имя вида wg*/nwg*/tun*/utun*, либо
#     интерфейса с таким именем в системе нет вовсе (типовой случай после
#     перехода с WG на RAW — мёртвый nwg1). Группа на существующем НЕ
#     туннельном интерфейсе (eth9, br0, ppp0) — чужая, не трогаем никогда.
#     Без этого правила починка разбора утащила бы за туннель и те группы,
#     которые владелец завёл под другую маршрутизацию.
#
#  3. Возврат — АДРЕСНЫЙ. prev-файл это таблица «ключ группы → интерфейс», и
#     в неё пишутся только те группы, которые мы реально переключили. Каждая
#     возвращается на своё значение, а не на одно общее. Старый однострочный
#     формат prev-файла понимается и используется как общий запасной вариант.
#
#  4. Переопределение из конфига: MT_GROUPS="id или имя, через запятую" в
#     qwdtt.conf отключает автоматику и работает ровно по списку. Пусто —
#     работает правило из пункта 2.
MT_CONF="/opt/var/lib/magitrickle/config.yaml"
MT_BAK="$MT_CONF.qwdtt-bak"
MT_INIT="/opt/etc/init.d/S99magitrickle"
MT_PREVF="/opt/etc/qwdtt/.magitrickle_prev_iface"
# Самый последний рубеж, если вернуть группу больше некуда: ни записи в
# prev-таблице, ни бэкапа, ни маршрута по умолчанию. Литерал оставлен только
# на этот случай — порядок источников см. mt_fallback_iface.
MT_DEFAULT_IF="nwg1"

mt_installed() { [ -f "$MT_CONF" ]; }

# Наш ли это интерфейс (tun самого qwdtt). Проверяем и "meridian", и текущий
# RAW_TUN: иначе при смене RAW_TUN значение "meridian", оставшееся в конфиге
# от прошлого запуска, было бы записано в prev-таблицу как «прежний
# WG-интерфейс» и возврат в WG уже никуда бы не вёл.
mt_is_own_iface() {
	[ "$1" = "meridian" ] && return 0
	[ -n "$RAW_TUN" ] && [ "$1" = "$RAW_TUN" ] && return 0
	return 1
}

# Есть ли такой интерфейс в системе. Отдельной функцией — её подменяют тесты.
mt_iface_exists() {
	[ -n "$1" ] || return 1
	[ -e "/sys/class/net/$1" ] && return 0
	ip -o link show "$1" >/dev/null 2>&1
}

# Имя выглядит туннельным.
mt_is_tunnel_name() {
	case "$1" in
		wg*|nwg*|tun*|utun*) return 0 ;;
	esac
	return 1
}

# "blackhole" — не интерфейс, а служебное значение MagiTrickle со смыслом
# «гасить трафик этой группы». Проверено по исходнику: это ЕДИНСТВЕННОЕ такое
# значение (константа Blackhole в utils/netfilterTools/ipset-to-link.go,
# сравнения r.ifaceName == Blackhole; API подставляет его первым пунктом
# списка интерфейсов в handlers.go). Ни unreachable, ни prohibit, ни throw у
# MagiTrickle нет.
MT_BLACKHOLE="blackhole"

mt_is_blackhole() { [ "$1" = "$MT_BLACKHOLE" ]; }

# «Своя» ли группа по её интерфейсу — правило из пункта 2 шапки.
mt_group_is_ours() {
	[ -n "$1" ] || return 1
	# Служебное значение проверяем ПЕРВЫМ. Иначе оно проваливается в правило
	# «интерфейса нет в системе — значит мёртвый туннель, наш» и мы утаскиваем
	# в туннель трафик, который владелец сознательно велел гасить.
	mt_is_blackhole "$1" && return 1
	mt_is_own_iface "$1" && return 0
	mt_is_tunnel_name "$1" && return 0
	# Интерфейса нет в системе — это мёртвый туннель, наш случай.
	mt_iface_exists "$1" || return 0
	return 1
}

# mt_groups_dump — по строке на каждую группу секции groups::
#     номер<TAB>ключ<TAB>имя<TAB>интерфейс
# Ключ — id, если он есть; иначе имя; иначе "#номер". Номер нужен, чтобы
# переписывать группы адресно, не завися от порядка ключей внутри группы.
# Файл параметром: то же самое читается и из резервной копии.
mt_groups_dump() {
	[ -f "$1" ] || return 1
	awk '
		function trim(v) {
			sub(/[ \t]*#.*$/, "", v)
			sub(/^[ \t]+/, "", v); sub(/[ \t]+$/, "", v)
			gsub(/^["\047]|["\047]$/, "", v)
			return v
		}
		function flush(  key, nm) {
			if (!started) return
			key = id; if (key == "") key = name; if (key == "") key = "#" idx
			# Имя не имеет права быть пустым: табуляция — IFS-пробельный символ,
			# и пустое поле в середине строки схлопнется при чтении в shell,
			# сдвинув интерфейс на место имени. Группа без имени тогда молча
			# выпадала бы из обработки.
			nm = name; if (nm == "") nm = key
			if (iface != "") printf "%d\t%s\t%s\t%s\n", idx, key, nm, iface
			started = 0
		}
		BEGIN { ing=0; gind=-1; keyind=-1; started=0; idx=0 }
		/^[Gg]roups:/ { flush(); ing=1; gind=-1; keyind=-1; next }
		/^---/        { flush(); ing=0; next }
		/^[^ \t#-]/   { flush(); ing=0 }
		ing {
			if (match($0, /^[ \t]*-/)) {
				ind = RLENGTH - 1
				if (gind < 0) gind = ind
				if (ind == gind) {
					flush()
					started = 1; idx++; id=""; name=""; iface=""
					keyind = (match($0, /^[ \t]*-[ \t]+/) ? RLENGTH : gind + 2)
				}
			}
			if (!started) next
			lead = (match($0, /^[ \t]*/) ? RLENGTH : 0)
			isdash = (match($0, /^[ \t]*-[ \t]+/) && lead == gind)
			if (lead != keyind && !isdash) next
			line = $0
			if (line ~ /^[ \t]*(-[ \t]+)?id:[ \t]*/ && id == "") {
				v = line; sub(/^[ \t]*(-[ \t]+)?id:[ \t]*/, "", v); id = trim(v)
			}
			if (line ~ /^[ \t]*(-[ \t]+)?name:[ \t]*/ && name == "") {
				v = line; sub(/^[ \t]*(-[ \t]+)?name:[ \t]*/, "", v); name = trim(v)
			}
			if (line ~ /^[ \t]*(-[ \t]+)?interface:[ \t]*/ && iface == "") {
				v = line; sub(/^[ \t]*(-[ \t]+)?interface:[ \t]*/, "", v); iface = trim(v)
			}
		}
		END { flush() }
	' "$1" 2>/dev/null
}

# Первое значение interface — только для логов и обратной совместимости.
mt_iface_of()      { mt_groups_dump "$1" | head -1 | cut -f4; }
mt_current_iface() { mt_iface_of "$MT_CONF"; }

# mt_set_ifaces "номер=интерфейс,номер=интерфейс" — переписать interface
# ровно в перечисленных группах. Возврат: 0 — файл реально изменился,
# 1 — менять было нечего (значит и перезапускать MagiTrickle не нужно).
mt_set_ifaces() {
	MAPSTR="$1"
	[ -n "$MAPSTR" ] || return 1
	TMPF="$MT_CONF.qwdtt-tmp"
	awk -v mapstr="$MAPSTR" '
		BEGIN {
			n = split(mapstr, a, ",")
			for (i = 1; i <= n; i++) { split(a[i], kv, "="); want[kv[1]] = kv[2] }
			ing=0; gind=-1; keyind=-1; started=0; idx=0
		}
		/^[Gg]roups:/ { ing=1; gind=-1; keyind=-1; started=0; print; next }
		/^---/        { ing=0; started=0; print; next }
		/^[^ \t#-]/   { ing=0; started=0 }
		{
			if (ing) {
				if (match($0, /^[ \t]*-/)) {
					ind = RLENGTH - 1
					if (gind < 0) gind = ind
					if (ind == gind) {
						started = 1; idx++
						keyind = (match($0, /^[ \t]*-[ \t]+/) ? RLENGTH : gind + 2)
					}
				}
				if (started && (idx in want)) {
					lead = (match($0, /^[ \t]*/) ? RLENGTH : 0)
					isdash = (match($0, /^[ \t]*-[ \t]+/) && lead == gind)
					if ((lead == keyind || isdash) && $0 ~ /^[ \t]*(-[ \t]+)?interface:[ \t]*/) {
						sub(/interface:.*$/, "interface: " want[idx])
					}
				}
			}
			print
		}
	' "$MT_CONF" > "$TMPF" 2>/dev/null || { rm -f "$TMPF"; return 1; }
	[ -s "$TMPF" ] || { rm -f "$TMPF"; return 1; }
	if cmp -s "$TMPF" "$MT_CONF"; then rm -f "$TMPF"; return 1; fi
	cat "$TMPF" > "$MT_CONF" 2>/dev/null || { rm -f "$TMPF"; return 1; }
	rm -f "$TMPF"
	return 0
}

mt_restart() {
	[ -x "$MT_INIT" ] || { echo "$(date): [magitrickle] $MT_INIT не найден — перезапуск пропущен" >> "$LOG"; return 1; }
	"$MT_INIT" restart >/dev/null 2>&1
	echo "$(date): [magitrickle] перезапущен" >> "$LOG"
}

# ---------- prev-таблица «ключ группы → прежний интерфейс» ----------

# Чтение с молчаливой миграцией старого формата: одна строка без табуляции —
# это прежний общий интерфейс, он становится записью с ключом "*" (общий
# запасной вариант). Ничего не теряем и ничего не переписываем на диске до
# ближайшего сохранения.
mt_prev_table_read() {
	[ -f "$MT_PREVF" ] || return 0
	awk -F'\t' '
		{ sub(/\r$/, "") }
		NF == 0 || $0 ~ /^[ \t]*$/ { next }
		NF >= 2 { print $1 "\t" $2; next }
		{ print "*\t" $1 }
	' "$MT_PREVF" 2>/dev/null
}

mt_prev_table_get() {
	[ -n "$1" ] || return 0
	mt_prev_table_read | awk -F'\t' -v k="$1" '$1 == k { print $2; exit }'
}

# Куда возвращать группу, для которой в таблице записи нет. Порядок источников:
#   1) общий запасной из старого формата prev-файла;
#   2) резервная копия конфига — первая группа с НЕ нашим интерфейсом;
#   3) интерфейс маршрута по умолчанию — он гарантированно живой; трафик пойдёт
#      мимо VPN, но пойдёт (лучше, чем увести группу на мёртвое имя);
#   4) MT_DEFAULT_IF — литерал, самый последний рубеж.
mt_default_route_iface() {
	ip route show default 2>/dev/null | awk '{ for (i=1;i<=NF;i++) if ($i=="dev") { print $(i+1); exit } }'
}

# Параметр — ключ группы, для которой ищем запасное значение. Без него
# работает только общая часть цепочки.
mt_fallback_iface() {
	MT_FB=$(mt_prev_table_get '*')
	if [ -n "$MT_FB" ] && ! mt_is_own_iface "$MT_FB"; then echo "$MT_FB"; return 0; fi
	# Из бэкапа берём значение ТОЙ ЖЕ группы по ключу, а не «первое чужое
	# среди групп»: на конфиге из трёх групп первое чужое — это чужая
	# настройка, и мы бы молча навязали её не той группе.
	if [ -n "$1" ] && [ -f "$MT_BAK" ]; then
		MT_FB=$(mt_groups_dump "$MT_BAK" | awk -F'\t' -v k="$1" '$2 == k { print $4; exit }')
		if [ -n "$MT_FB" ] && ! mt_is_own_iface "$MT_FB"; then echo "$MT_FB"; return 0; fi
	fi
	# Той же группы в бэкапе нет (появилась позже, переименовали, бэкапа нет) —
	# идём дальше: живой интерфейс маршрута по умолчанию. Трафик пойдёт мимо
	# туннеля, но пойдёт; это лучше, чем увести группу на мёртвое имя.
	MT_FB=$(mt_default_route_iface)
	if [ -n "$MT_FB" ] && ! mt_is_own_iface "$MT_FB"; then echo "$MT_FB"; return 0; fi
	echo "$MT_DEFAULT_IF"
}

# Совместимость: раньше так называлась «куда возвращать». Внешних вызовов нет,
# но функция дешёвая, а чужие скрипты и привычка живучи.
mt_prev_iface() { mt_fallback_iface "$1"; }

# Запомнить прежние интерфейсы ТЕХ групп, которые мы собираемся переключить.
# На вход — строки "номер<TAB>ключ<TAB>интерфейс". Слияние с уже записанным:
# новые записи побеждают, старые по другим ключам сохраняются.
mt_save_prev_for() {
	[ -f "$MT_BAK" ] || cp "$MT_CONF" "$MT_BAK" 2>/dev/null
	mkdir -p "$(dirname "$MT_PREVF")" 2>/dev/null
	MT_NEWROWS=$(printf '%s\n' "$1" | awk -F'\t' 'NF >= 3 && $3 != "" { print $2 "\t" $3 }')
	[ -n "$MT_NEWROWS" ] || return 0
	{ printf '%s\n' "$MT_NEWROWS"; mt_prev_table_read; } \
		| awk -F'\t' 'NF >= 2 && $1 != "" && !seen[$1]++ { print $1 "\t" $2 }' \
		> "$MT_PREVF.tmp" 2>/dev/null || return 0
	[ -s "$MT_PREVF.tmp" ] || { rm -f "$MT_PREVF.tmp"; return 0; }
	mv -f "$MT_PREVF.tmp" "$MT_PREVF" 2>/dev/null
	echo "$(date): [magitrickle] запомнил прежние интерфейсы групп: $(printf '%s' "$MT_NEWROWS" | tr '\t' '=' | tr '\n' ' ')" >> "$LOG"
}

# Группы, которые нам МОЖНО трогать. Печатает "номер<TAB>ключ<TAB>интерфейс".
mt_target_groups() {
	mt_groups_dump "$MT_CONF" | while IFS='	' read -r MT_IDX MT_KEY MT_NAME MT_IF; do
		[ -n "$MT_IF" ] || continue
		if [ -n "$MT_GROUPS" ]; then
			# Явный список из конфига — автоматика выключена, работаем по нему.
			case ",$MT_GROUPS," in
				*",$MT_KEY,"*|*",$MT_NAME,"*) printf '%s\t%s\t%s\n' "$MT_IDX" "$MT_KEY" "$MT_IF" ;;
			esac
			continue
		fi
		# Группа, которую мы когда-то трогали, остаётся нашей навсегда —
		# независимо от того, на каком интерфейсе стоит сейчас. Без этого
		# получается билет в один конец: один раз увели группу на запасной
		# интерфейс (или на blackhole), и по правилу «своих» она уже чужая,
		# в туннель не вернётся никогда, а домены владельца останутся мимо
		# туннеля или погашенными до ручного вмешательства.
		if [ -n "$(mt_prev_table_get "$MT_KEY")" ]; then
			printf '%s\t%s\t%s\n' "$MT_IDX" "$MT_KEY" "$MT_IF"; continue
		fi
		mt_group_is_ours "$MT_IF" && printf '%s\t%s\t%s\n' "$MT_IDX" "$MT_KEY" "$MT_IF"
	done
}

# Безусловный возврат НАШИХ групп на прежние интерфейсы. Вызывается при stop,
# при переходе в режим wg и в watchdog при мёртвом туннеле — то есть везде,
# где трафик через наш tun заведомо не пойдёт. Группы, которых мы не касались,
# не трогаются и здесь.
mt_restore_prev() {
	mt_installed || return 0
	MT_DUMP=$(mt_groups_dump "$MT_CONF")
	if [ -z "$MT_DUMP" ]; then
		echo "$(date): [magitrickle] в конфиге не нашлось ни одной группы — возвращать нечего" >> "$LOG"
		return 0
	fi
	MT_MAP=""; MT_SAID=""; MT_FBUSED=""; MT_LEARN=""
	MT_TMPLIST="$MT_PREVF.dump"
	printf '%s\n' "$MT_DUMP" > "$MT_TMPLIST" 2>/dev/null
	while IFS='	' read -r MT_IDX MT_KEY MT_NAME MT_IF; do
		[ -n "$MT_IF" ] || continue
		# Возвращаем только то, что стоит на НАШЕМ tun. Всё остальное — чужое
		# либо нетронутое, и трогать его при возврате нельзя.
		mt_is_own_iface "$MT_IF" || continue
		MT_WANT=$(mt_prev_table_get "$MT_KEY")
		if [ -z "$MT_WANT" ] || mt_is_own_iface "$MT_WANT"; then
			# Записи нет: группу переименовали/пересоздали, prev-файл потеряли,
			# либо владелец сам поставил наш tun. Уходим по общему запасному.
			MT_WANT=$(mt_fallback_iface "$MT_KEY")
			MT_FBUSED="$MT_FBUSED $MT_KEY"
			# Запоминаем выбор запасной цепочки: во-первых, чтобы больше не
			# гадать, во-вторых — этим группа помечается нашей и вернётся в
			# туннель, когда он поднимется.
			MT_LEARN="$MT_LEARN$MT_IDX\t$MT_KEY\t$MT_WANT\n"
		fi
		[ -n "$MT_WANT" ] || continue
		MT_MAP="${MT_MAP:+$MT_MAP,}$MT_IDX=$MT_WANT"
		MT_SAID="$MT_SAID $MT_KEY→$MT_WANT"
		# Возвращаем ровно то, что было записано, даже если интерфейса больше
		# нет: молчаливое «улучшение» чужой настройки хуже точного возврата.
		# Но молчать об этом нельзя — иначе владелец узнает о мёртвых доменах
		# через неделю по жалобе клиента, а не сейчас.
		if mt_is_blackhole "$MT_WANT"; then
			# Не сбой и не мёртвый интерфейс: владелец выбрал не течь мимо
			# туннеля. Переписывать его выбор на «живой» интерфейс нельзя,
			# но и молчать нельзя — иначе «перестал работать ютуб» будет
			# выглядеть поломкой нашего клиента.
			echo "$(date): [magitrickle] возврат группы \"$MT_NAME\": $MT_IF -> $MT_WANT (домены этой группы не будут работать, пока туннель не поднимется — это настройка MagiTrickle, а не сбой)" >> "$LOG"
		elif ! mt_iface_exists "$MT_WANT"; then
			echo "$(date): [magitrickle] возврат группы \"$MT_NAME\": $MT_IF -> $MT_WANT (ВНИМАНИЕ: $MT_WANT в системе отсутствует, домены этой группы работать не будут)" >> "$LOG"
		fi
	done < "$MT_TMPLIST"
	rm -f "$MT_TMPLIST"
	if [ -z "$MT_MAP" ]; then
		echo "$(date): [magitrickle] возвращать нечего: групп на нашем tun нет" >> "$LOG"
		return 0
	fi
	[ -n "$MT_LEARN" ] && mt_save_prev_for "$(printf "$MT_LEARN")"
	if mt_set_ifaces "$MT_MAP"; then
		echo "$(date): [magitrickle] интерфейсы групп возвращены:$MT_SAID" >> "$LOG"
		[ -n "$MT_FBUSED" ] && echo "$(date): [magitrickle] по запасному варианту (записи в таблице не было):$MT_FBUSED" >> "$LOG"
		mt_restart
	fi
}

# Туннель реально пропускает трафик? Именно это, а не факт существования
# процесса или интерфейса, решает, можно ли заворачивать в него группы.
mt_tunnel_alive() {
	ping -c 2 -W 5 -I "${RAW_TUN:-meridian}" 8.8.8.8 >/dev/null 2>&1
}

# Перевести НАШИ группы на наш tun — только если туннель проверен пингом.
# Возврат: 0 — переключать больше нечего либо переключили, 1 — туннель мёртв.
mt_apply_raw_if_alive() {
	mt_installed || return 0
	MT_IF="${RAW_TUN:-meridian}"
	MT_TARGETS=$(mt_target_groups)
	if [ -z "$MT_TARGETS" ]; then
		# Молча не переключаем и молча не молчим: одна внятная строка.
		echo "$(date): [magitrickle] ни одной своей группы не нашлось (все стоят на существующих не туннельных интерфейсах или групп нет) — ничего не трогаю. Если это неверно, задай MT_GROUPS в qwdtt.conf" >> "$LOG"
		return 0
	fi
	MT_TODO=$(printf '%s\n' "$MT_TARGETS" | awk -F'\t' -v own="$MT_IF" '$3 != own { print }')
	[ -n "$MT_TODO" ] || return 0
	if ! mt_tunnel_alive; then
		echo "$(date): [magitrickle] туннель $MT_IF не отвечает на ping — интерфейс групп оставлен прежним" >> "$LOG"
		return 1
	fi
	mt_save_prev_for "$MT_TODO"
	MT_MAP=$(printf '%s\n' "$MT_TODO" | awk -F'\t' -v new="$MT_IF" '{ printf "%s%s=%s", (NR>1 ? "," : ""), $1, new }')
	if mt_set_ifaces "$MT_MAP"; then
		echo "$(date): [magitrickle] туннель проверен пингом, на $MT_IF переведены группы: $(printf '%s\n' "$MT_TODO" | cut -f2 | tr '\n' ' ')" >> "$LOG"
		mt_restart
	fi
	return 0
}

# Фоновый ожидатель: крутится после запуска клиента и переключает группы, как
# только туннель поднимется. Раньше переключение делалось безусловно в момент
# старта — и если туннель не поднимался, у клиента пропадал интернет по всем
# доменам из групп. Если не дождались за отведённое время — группы остаются на
# прежнем интерфейсе, а следующий прогон watchdog (раз в 5 мин) попробует снова.
mt_raw_switch_when_up() {
	mt_installed || return 0
	i=0
	while [ "$i" -lt 12 ]; do
		mt_apply_raw_if_alive && return 0
		sleep 5
		i=$((i+1))
	done
	echo "$(date): [magitrickle] туннель не поднялся за отведённое время — переключение отложено до watchdog" >> "$LOG"
}

# При старте в RAW только снимаем резервную копию конфига; само переключение и
# запоминание прежних интерфейсов делает mt_apply_raw_if_alive после проверки
# туннеля пингом — запоминать до неё нечего, мы ещё ничего не меняли.
mt_sync_mode() {
	if [ "${MODE:-raw}" = "raw" ]; then
		mt_installed || return 0
		[ -f "$MT_BAK" ] || cp "$MT_CONF" "$MT_BAK" 2>/dev/null
	else
		mt_restore_prev
	fi
}
# --- конец блока MagiTrickle -------------------------------------------------

# Самоустановка watchdog в cron — чтобы клиенту не нужно было лезть в консоль.
# Вызывается при каждом start; если задача уже есть — ничего не делает.
ensure_cron() {
	CRONFILE="/opt/etc/crontabs/root"
	CRONLINE="*/5 * * * * /opt/etc/init.d/S99qwdtt watchdog >/dev/null 2>&1"
	mkdir -p /opt/etc/crontabs 2>/dev/null
	[ -f "$CRONFILE" ] || touch "$CRONFILE"
	if ! grep -q "S99qwdtt watchdog" "$CRONFILE" 2>/dev/null; then
		echo "$CRONLINE" >> "$CRONFILE"
		echo "$(date): watchdog добавлен в cron (проверка каждые 5 мин)" >> "$LOG"
		# перечитать расписание
		for c in /opt/etc/init.d/S*cron*; do [ -x "$c" ] && "$c" restart >/dev/null 2>&1 && break; done
	fi
	# убедиться, что сам crond запущен
	if ! ps w | grep -q '[c]rond'; then
		crond -c /opt/etc/crontabs >/dev/null 2>&1 || true
	fi
}

start() {
	[ -x "$BIN" ] || { echo "нет $BIN"; exit 1; }
	rm -f "$STOPFLAG" 2>/dev/null
	ensure_cron
	mkdir -p "$(dirname "$LOG")" 2>/dev/null
	mt_sync_mode
	if is_running; then echo "уже запущен"; return 0; fi
	mkdir -p "$(dirname "$LOG")" "$(dirname "$PIDF")"
	rotate_log
	# Отметка «доставка уже пробовала» относится к ТЕКУЩЕМУ старту — сбрасываем её
	# здесь, иначе на следующем старте сообщение соврёт про попытку, которой ещё не было.
	rm -f "$ROUTE_TRIED" 2>/dev/null
	route_check_sum
	UPTIME=$(cut -d. -f1 /proc/uptime 2>/dev/null || echo 999999)
	DELAY="${DELAY_MIN:-0}"
	if [ "$UPTIME" -lt 120 ] 2>/dev/null; then
		sync_time_if_needed
		if [ "$DELAY" -gt 0 ] 2>/dev/null; then
			echo "загрузка роутера — задержка ${DELAY} мин перед запуском"
			( sleep $((DELAY*60)); sync_time_if_needed; rm -f "$PENDF"; launch_locked ) &
			echo $! > "$PENDF"
		else
			launch_locked
		fi
	else
		launch_locked
	fi
}

# STOPFLAG — маркер намеренной остановки администратором (кнопка "Стоп" в
# панели или qwdtt-ctl stop). Без него watchdog видел просто "процесса нет"
# и через пару минут поднимал туннель обратно, игнорируя явное решение
# человека его выключить. Внутренние перезапуски (сам watchdog, restart)
# используют stop_internal и флаг не ставят.
STOPFLAG="/opt/var/run/qwdtt.stopped"

stop_internal() {
	[ -f "$PENDF" ] && kill "$(cat "$PENDF")" 2>/dev/null; rm -f "$PENDF"
	[ -f "$PIDF" ] && kill "$(cat "$PIDF")" 2>/dev/null; rm -f "$PIDF"
	for p in $(ps w | grep -E '[q]wdtt (-peer|-mode)' | awk '{print $1}'); do kill -9 "$p" 2>/dev/null; done
	# NAT снимаем последним: пока процесс жив, правило ещё нужно. Иначе
	# правила копились бы с каждым перезапуском.
	remove_masq
	route_call on-tunnel-down
}

stop() {
	mkdir -p "$(dirname "$STOPFLAG")" 2>/dev/null
	date +%s > "$STOPFLAG" 2>/dev/null
	stop_internal
	# Туннеля больше нет — группы MagiTrickle обязаны уйти с нашего tun,
	# иначе выключение клиента = потеря интернета по всем доменам из групп.
	mt_restore_prev
	echo "остановлен"
}

restart() { stop; sleep 2; start; }

status() {
	if [ -f "$PENDF" ] && kill -0 "$(cat "$PENDF")" 2>/dev/null; then
		echo "ожидание отложенного запуска после перезагрузки"
	elif is_running; then
		echo "работает"
	else
		echo "остановлен"
	fi
}

# watchdog: вызывается из cron раз в несколько минут.
# Поднимает процесс, если он умер, подрезает разросшийся лог,
# и раз в час проверяет/чинит системное время (см. periodic_time_check).
watchdog() {
	rotate_log
	periodic_time_check
	# Туннель выключен намеренно (кнопка "Стоп" / qwdtt-ctl stop) — не
	# воскрешаем его вопреки решению администратора. Снимается только
	# явным start.
	if [ -f "$STOPFLAG" ]; then
		exit 0
	fi
	# если ждём отложенного запуска после перезагрузки — не вмешиваемся
	if [ -f "$PENDF" ] && kill -0 "$(cat "$PENDF")" 2>/dev/null; then
		exit 0
	fi
	if ! is_running; then
		echo "$(date): [watchdog] процесс не найден, поднимаю" >> "$LOG"
		launch_locked
		exit 0
	fi
	# порт 127.0.0.1:9000 существует только в режиме WG (локальный мост
	# к нативному WG-интерфейсу роутера) — в RAW-режиме процесс его
	# никогда не открывает, это нормально, а не поломка. Раньше эта
	# проверка была безусловной и убивала+пересоздавала рабочий RAW-туннель
	# каждые 5 минут, считая его зависшим.
	if [ "${MODE:-raw}" != "raw" ]; then
		if ! netstat -ln 2>/dev/null | grep -q '127.0.0.1:9000'; then
			echo "$(date): [watchdog] процесс жив, но порт 9000 не слушает — перезапускаю" >> "$LOG"
			stop_internal; sleep 2; launch_now
		fi
	else
		# RAW-режим: процесс может формально быть жив (is_running=true),
		# пока внутренняя DTLS/TURN-сессия внутри него уже мертва —
		# наблюдалось на практике многократно: qwdtt-ctl status показывает
		# "РАБОТАЕТ", но реального трафика через meridian нет вообще
		# (100% потерь). Проверяем не факт существования процесса, а то,
		# что тоннель РЕАЛЬНО пропускает трафик.
		RAW_TUN_NAME="${RAW_TUN:-meridian}"
		if ! ping -c 2 -W 5 -I "$RAW_TUN_NAME" 8.8.8.8 >/dev/null 2>&1; then
			echo "$(date): [watchdog] RAW-туннель не пропускает трафик (ping через $RAW_TUN_NAME не прошёл) — перезапускаю" >> "$LOG"
			# ПЕРВЫМ делом уводим группы MagiTrickle с мёртвого tun: перезапуск
			# занимает десятки секунд, и всё это время клиент не должен сидеть
			# без интернета по доменам из групп. Обратно группы вернёт фоновый
			# ожидатель из launch_now, когда пинг через tun снова пройдёт.
			mt_restore_prev
			stop_internal
			sleep 2
			ip link show "$RAW_TUN_NAME" >/dev/null 2>&1 && ip link delete "$RAW_TUN_NAME" 2>/dev/null
			launch_locked
		else
			# Туннель жив — группы должны стоять на нём. Нужно после аварийного
			# отката и на случай, если при старте туннель ещё не успел подняться
			# и фоновый ожидатель сдался раньше времени.
			mt_apply_raw_if_alive
			# Тем же порядком подтверждаем NAT: правило волатильное, могло
			# исчезнуть вместе с пересозданным интерфейсом или после ручного
			# вмешательства. Вызов идемпотентен — при уже стоящем правиле это
			# одна проверка -C и выход.
			ensure_masq
			route_call ensure
		fi
	fi
	# Повтор доставки — ПОСЛЕДНИМ делом сторожа: попытка может занять до
	# ROUTE_TOTAL_MAX секунд, и она не должна задерживать подъём клиента.
	route_retry
}

case "$1" in
	start) start ;; stop) stop ;; restart) restart ;; status) status ;;
	watchdog) watchdog ;;
	route-wait) route_wait ;;
	*) echo "usage: $0 {start|stop|restart|status|watchdog}" ;;
esac
